/// Map a language tag to one or more candidate syntect syntax names, in order
/// of preference. The first one that exists in the loaded `SyntaxSet` wins.
///
/// Multiple candidates preserve useful highlighting if an older generated
/// dump is accidentally paired with newer alias code.
fn resolve_alias(lang: &str) -> &'static [&'static str] {
    match lang {
        "ts" | "typescript" => &["TypeScript", "JavaScript"],
        "tsx" => &["TypeScriptReact", "TypeScript", "JavaScript"],
        "js" | "javascript" => &["JavaScript"],
        "jsx" => &["JavaScript"],
        "rs" | "rust" => &["Rust"],
        "py" | "python" => &["Python"],
        "sh" | "bash" | "zsh" => &["Bourne Again Shell (bash)", "Bash"],
        "md" | "markdown" => &["Markdown"],
        // mdx has no dedicated grammar; treat as Markdown so fences get theming
        "mdx" => &["Markdown"],
        "yaml" | "yml" => &["YAML"],
        "json" => &["JSON"],
        "c" => &["C"],
        "cpp" | "c++" => &["C++"],
        "go" => &["Go"],
        "toml" => &["TOML"],
        "html" => &["HTML"],
        "css" => &["CSS"],
        _ => &[],
    }
}

/// Lowercase + collapse non-alphanumerics to `-` (no leading/trailing dashes,
/// no doubled dashes).
fn theme_slug(name: &str) -> String {
    let mut out = String::with_capacity(name.len());
    let mut last_dash = true; // suppress leading dash
    for ch in name.chars() {
        if ch.is_ascii_alphanumeric() {
            for c in ch.to_lowercase() {
                out.push(c);
            }
            last_dash = false;
        } else if !last_dash {
            out.push('-');
            last_dash = true;
        }
    }
    if out.ends_with('-') {
        out.pop();
    }
    out
}

/// Build a [`HighlightedLines`] for the fallback path (unknown lang or
/// tokenization error). Splits `code` on `LinesWithEndings` so the per-line
/// vector has the same granularity as the normal path.
fn fallback_lines(code: &str, slug: &str) -> HighlightedLines {
    let lines: Vec<String> = LinesWithEndings::from(code).map(escape_html).collect();
    HighlightedLines {
        theme_slug: slug.to_string(),
        lines,
        fallback: true,
    }
}

/// Format a syntect [`Color`] as a lowercase `#rrggbb` string, dropping alpha.
///
/// Matches the RGB branch of syntect's own `write_css_color`
/// (`#{:02x}{:02x}{:02x}`) so the colours emitted in `--shiki-*` vars are
/// byte-identical to what the single `color:` path would emit — minus the alpha
/// channel, which is intentionally dropped for the dual custom-property form.
fn color_to_hex(c: Color) -> String {
    format!("#{:02x}{:02x}{:02x}", c.r, c.g, c.b)
}

/// Build a [`DualHighlightedLines`] for the dual fallback path (unknown lang,
/// tokenization error, or region-alignment mismatch). Splits `code` on
/// `LinesWithEndings` so the per-line vector matches the normal path's
/// granularity; each line is HTML-escaped with no colour vars. Background vars
/// are preserved (the themes resolved fine; only tokenization fell back).
fn dual_fallback_lines(
    code: &str,
    light_bg: Option<String>,
    dark_bg: Option<String>,
) -> DualHighlightedLines {
    let lines: Vec<String> = LinesWithEndings::from(code).map(escape_html).collect();
    DualHighlightedLines {
        lines,
        light_bg,
        dark_bg,
        fallback: true,
    }
}

/// Build a [`ClassHighlightedLines`] for the class-mode fallback path (unknown
/// lang or a parse/apply error). Splits `code` on `LinesWithEndings` so the
/// per-line vector matches the normal path's granularity; each line is
/// HTML-escaped with no token spans.
fn class_fallback_lines(code: &str, reason: ClassHighlightFallbackReason) -> ClassHighlightedLines {
    let lines: Vec<String> = LinesWithEndings::from(code).map(escape_html).collect();
    ClassHighlightedLines {
        lines,
        fallback: true,
        fallback_reason: Some(reason),
    }
}

/// Render the class-mode wrapper around already escaped per-line fragments.
///
/// This is intentionally separate from syntax tokenization: direct callers
/// receive its exact HTML, while the Markdown plugin receives the same line
/// fragments to retain structured HAST nodes for code-enrichment visitors.
fn render_class_highlight_markup(root_class: &str, lines: &[String]) -> String {
    let mut html = String::with_capacity(
        root_class.len()
            + lines.iter().map(String::len).sum::<usize>()
            + lines.len() * "<span class=\"line\"></span>".len()
            + "<pre class=\"\"><code></code></pre>".len(),
    );
    html.push_str("<pre class=\"");
    html.push_str(&escape_html(root_class));
    html.push_str("\"><code>");
    for line in lines {
        html.push_str("<span class=\"line\">");
        html.push_str(line);
        html.push_str("</span>");
    }
    html.push_str("</code></pre>");
    html
}

/// `classPrefix` validation: non-empty, first char an ASCII letter, remaining
/// chars ASCII alphanumeric, `_`, or `-`.
fn is_valid_class_prefix(s: &str) -> bool {
    let mut chars = s.chars();
    match chars.next() {
        Some(c) if c.is_ascii_alphabetic() => {}
        _ => return false,
    }
    chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-')
}

