//! Syntect-based syntax highlighting.
//!
//! Provides a [`Highlighter`] cache around syntect's [`SyntaxSet`] and
//! [`ThemeSet`], plus an [`Highlighter::highlight`] entry point that returns
//! an HTML fragment of the form
//! `<pre class="syntect-{theme-slug}"><code>…spans…</code></pre>`.
//!
//! The class on the `<pre>` element lets users theme blocks via CSS while still
//! getting syntect-coloured spans inside.
//!
//! ## Bundled-set caching
//!
//! Deserializing syntect's bundled `SyntaxSet` and `ThemeSet` is expensive
//! (several milliseconds each). Both are loaded **once per process** via
//! [`BUNDLED_SYNTAX_SET`] and [`BUNDLED_THEME_SET`] (`std::sync::LazyLock`),
//! then shared — `Highlighter` borrows the syntax set via `Arc` and clones
//! only the theme map when user-supplied `.tmTheme` files must be layered on
//! top of the defaults.

// Backend contract (zfb#1573): without one of these features, syntect itself
// fails first with E0433 `regex_impl` errors (its parsing::regex has no
// implementation), so plain builds never reach this guard — it exists for
// tooling that type-checks this crate against a pre-built graph, and to make
// the feature contract greppable at the point of use.
#[cfg(not(any(feature = "syntect-onig", feature = "syntect-fancy")))]
compile_error!(
    "zfb-content needs a syntect regex backend: enable feature `syntect-onig` (native default) or `syntect-fancy` (wasm-safe); `default-features = false` alone leaves syntect without a regex implementation"
);

use std::collections::BTreeMap;
use std::path::Path;
use std::sync::{Arc, LazyLock};

use syntect::easy::{HighlightLines, ScopeRegionIterator};
use syntect::highlighting::{Color, Theme, ThemeSet};
use syntect::html::{styled_line_to_highlighted_html, IncludeBackground};
use syntect::parsing::{ParseState, ScopeStack, SyntaxSet};
use syntect::util::LinesWithEndings;
use zfb_types::escape_html;

use crate::hi_roles::classify;

/// Default prefix for semantic class-mode code highlighting.
///
/// Kept beside the renderer so native config and direct consumers (including
/// the WASM facade) cannot grow independent defaults.
pub const DEFAULT_CLASS_HIGHLIGHT_PREFIX: &str = "hi-";

/// The custom `SyntaxSet` dump (issue #1848): syntect's own bundled defaults
/// plus the TOML, TypeScript, and TSX grammars committed under
/// `assets/syntaxes/`, regenerated by `tests/bin/generate_syntax_dump.rs`.
/// `SyntaxSet` is immutable after `SyntaxSetBuilder::build()`, so there is no
/// way to merge extra grammars into `load_defaults_newlines()`'s result at
/// runtime — this dump is a full replacement built ahead of time instead.
static BUNDLED_SYNTAX_SET_DUMP: &[u8] = include_bytes!("../assets/syntax-set.packdump");

/// Bundled `SyntaxSet` loaded once per process.
///
/// `SyntaxSet::from_uncompressed_data` deserializes the dump embedded above.
/// The call is safe to make from any thread; `LazyLock` ensures it happens
/// exactly once. Dumps store regex patterns as strings with lazy
/// per-backend compilation, so this one dump correctly serves both the
/// native `onig` backend and the wasm `fancy` backend.
static BUNDLED_SYNTAX_SET: LazyLock<Arc<SyntaxSet>> = LazyLock::new(|| {
    Arc::new(
        syntect::dumps::from_uncompressed_data(BUNDLED_SYNTAX_SET_DUMP)
            .expect("assets/syntax-set.packdump must deserialize; regenerate with `cargo run -p zfb-content --bin generate_syntax_dump --features generate-syntax-dump`"),
    )
});

/// Test-only accessor for the process-wide bundled syntax set — lets other
/// modules' tests (e.g. `hi_roles`) exercise the SAME custom dump
/// `Highlighter` uses instead of duplicating `SyntaxSet::load_defaults_newlines()`
/// (which lacks the extra grammars above).
#[cfg(test)]
pub(crate) fn bundled_syntax_set_for_tests() -> Arc<SyntaxSet> {
    Arc::clone(&BUNDLED_SYNTAX_SET)
}

/// Bundled `ThemeSet` loaded once per process.
///
/// `ThemeSet::load_defaults()` deserializes the bundled themes. Loaded once
/// and shared via `Arc`; per-Pipeline user themes are layered on a clone of
/// `theme_set` so the base is never mutated.
static BUNDLED_THEME_SET: LazyLock<Arc<ThemeSet>> =
    LazyLock::new(|| Arc::new(ThemeSet::load_defaults()));

/// A single `.tmTheme` parse failure, carrying the file path.
#[derive(Debug)]
pub struct ThemeFileError {
    pub path: std::path::PathBuf,
    pub message: String,
}

impl std::fmt::Display for ThemeFileError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}: {}", self.path.display(), self.message)
    }
}

/// Cached syntect resources.
///
/// The `syntax_set` is shared across all `Highlighter` instances via `Arc`
/// (pointing at [`BUNDLED_SYNTAX_SET`]). The `theme_set` starts as a clone of
/// [`BUNDLED_THEME_SET`] so that per-Pipeline user themes can be inserted
/// without affecting the shared base.
pub struct Highlighter {
    /// Shared reference to the process-wide bundled syntax set.
    syntax_set: Arc<SyntaxSet>,
    /// Per-instance theme map — starts as a clone of [`BUNDLED_THEME_SET`] so
    /// user-supplied `.tmTheme` files can be layered on without mutating the
    /// shared base.
    theme_set: ThemeSet,
    default_theme: String,
}

impl Highlighter {
    /// Construct with bundled defaults (syntect's `load_defaults_newlines` syntaxes
    /// and the built-in theme set).
    ///
    /// Bundled defaults give us at minimum:
    /// `base16-ocean.dark`, `base16-ocean.light`, `InspiredGitHub`,
    /// `Solarized (dark)`, `Solarized (light)`.
    ///
    /// The bundled `SyntaxSet` is shared via [`BUNDLED_SYNTAX_SET`] (loaded once
    /// per process). The `ThemeSet` is cloned from [`BUNDLED_THEME_SET`] so
    /// per-instance user themes can be added without affecting the shared base.
    pub fn new() -> Self {
        // Clone the theme map from the shared base so user-supplied themes can
        // be inserted without affecting other Highlighter instances.
        // `ThemeSet` itself doesn't implement `Clone`, but `Theme` does, so we
        // manually copy the map.
        let theme_set = ThemeSet {
            themes: BUNDLED_THEME_SET
                .themes
                .iter()
                .map(|(k, v)| (k.clone(), v.clone()))
                .collect(),
        };
        Self {
            syntax_set: Arc::clone(&BUNDLED_SYNTAX_SET),
            theme_set,
            default_theme: "base16-ocean.dark".to_string(),
        }
    }

    /// List built-in theme names.
    pub fn theme_names(&self) -> Vec<String> {
        let mut names: Vec<String> = self.theme_set.themes.keys().cloned().collect();
        names.sort();
        names
    }

    /// Set the default theme used when callers don't pass one.
    /// Returns `Err` if the theme isn't loaded.
    pub fn set_default_theme(&mut self, name: &str) -> Result<(), HighlightError> {
        if !self.theme_set.themes.contains_key(name) {
            return Err(HighlightError::UnknownTheme(name.to_string()));
        }
        self.default_theme = name.to_string();
        Ok(())
    }

    /// Load extra `.tmTheme` files from `dir`.
    ///
    /// Each `.tmTheme` file is parsed individually.  On the first parse
    /// failure the function returns [`HighlightError::ThemeFileParse`] with
    /// the failing file's path attached — this is the acceptance-criterion
    /// "surface file path + parse error" guarantee.  IO errors reading the
    /// directory itself are returned as [`HighlightError::ThemeLoad`].
    ///
    /// The directory **must exist** before calling this function.  A missing
    /// directory is reported as an [`HighlightError::ThemeLoad`] IO error.
    pub fn load_themes_from_dir(&mut self, dir: &Path) -> Result<(), HighlightError> {
        let entries = std::fs::read_dir(dir)?;
        for entry in entries {
            let entry = entry?;
            let path = entry.path();
            if path.extension().and_then(|e| e.to_str()) != Some("tmTheme") {
                continue;
            }
            // Parse the individual file so we can attach its path to any error.
            let theme = ThemeSet::get_theme(&path).map_err(|e| {
                HighlightError::ThemeFileParse(ThemeFileError {
                    path: path.clone(),
                    message: e.to_string(),
                })
            })?;
            // Derive the theme name from its plist `name` key (already stored
            // in `theme.name`) or fall back to the file stem so the theme
            // is always addressable.
            let name = theme
                .name
                .as_deref()
                .filter(|n| !n.is_empty())
                .map(|n| n.to_string())
                .unwrap_or_else(|| {
                    path.file_stem()
                        .and_then(|s| s.to_str())
                        .unwrap_or("unknown")
                        .to_string()
                });
            self.theme_set.themes.insert(name, theme);
        }
        Ok(())
    }

    /// Resolve a fence language tag to a bundled syntax, applying the
    /// [`resolve_alias`] table. Shared by every highlight path
    /// ([`Self::highlight_lines`], [`Self::highlight_lines_dual`],
    /// [`Self::highlight_lines_classes`]) so alias handling lives in one place.
    /// `None`/empty `lang` or an unresolvable tag yields `None`, and each
    /// caller degrades to its own escaped fallback.
    fn resolve_syntax(&self, lang: Option<&str>) -> Option<&syntect::parsing::SyntaxReference> {
        lang.filter(|s| !s.is_empty()).and_then(|l| {
            self.syntax_set.find_syntax_by_token(l).or_else(|| {
                resolve_alias(l)
                    .iter()
                    .find_map(|name| self.syntax_set.find_syntax_by_name(name))
            })
        })
    }

    /// Highlight a code block.
    ///
    /// * `code` - raw source code (no surrounding HTML).
    /// * `lang` - language identifier from the markdown fence (`"rust"`, `"ts"`,
    ///   `"javascript"`, …). `None` or empty falls back to plain text.
    /// * `theme` - optional theme override; falls back to the configured default.
    ///
    /// Returns an HTML fragment of the form
    /// `<pre class="syntect-{theme-slug}"><code>…spans…</code></pre>`.
    /// `{theme-slug}` is the theme name lowercased with non-alphanumerics
    /// collapsed to `'-'`.
    ///
    /// If `lang` is unknown, returns the safe fallback
    /// `<pre><code>{html-escaped code}</code></pre>`.
    pub fn highlight(
        &self,
        code: &str,
        lang: Option<&str>,
        theme: Option<&str>,
    ) -> Result<String, HighlightError> {
        let result = self.highlight_lines(code, lang, theme)?;
        let spans: String = result.lines.concat();
        Ok(format!(
            "<pre class=\"syntect-{}\"><code>{spans}</code></pre>",
            result.theme_slug
        ))
    }

    /// Highlight a code block, returning per-line HTML fragments and the theme
    /// slug rather than a single HTML string.
    ///
    /// * `code` - raw source code (no surrounding HTML).
    /// * `lang` - language identifier from the markdown fence.
    /// * `theme` - optional theme override; falls back to the configured default.
    ///
    /// Returns a [`HighlightedLines`] value carrying:
    /// - `theme_slug`: the CSS-safe theme name (used as the `syntect-{slug}`
    ///   class on `<pre>`).
    /// - `lines`: one HTML fragment per source line (from
    ///   `styled_line_to_highlighted_html`). On the fallback path (unknown lang
    ///   or tokenization error) each line is the HTML-escaped source text with
    ///   a trailing newline preserved; the `fallback` flag is `true` in that case.
    pub fn highlight_lines(
        &self,
        code: &str,
        lang: Option<&str>,
        theme: Option<&str>,
    ) -> Result<HighlightedLines, HighlightError> {
        // Normalize empty theme to the configured default for symmetry with `lang`.
        let theme_name = theme
            .filter(|s| !s.is_empty())
            .unwrap_or(&self.default_theme);
        let theme_obj: &Theme = self
            .theme_set
            .themes
            .get(theme_name)
            .ok_or_else(|| HighlightError::UnknownTheme(theme_name.to_string()))?;

        let slug = theme_slug(theme_name);

        let syntax = self.resolve_syntax(lang);

        let Some(syntax) = syntax else {
            return Ok(fallback_lines(code, &slug));
        };

        let mut h = HighlightLines::new(syntax, theme_obj);
        let mut lines: Vec<String> = Vec::new();
        for line in LinesWithEndings::from(code) {
            let regions = match h.highlight_line(line, &self.syntax_set) {
                Ok(r) => r,
                // Path B: tokenization error — degrade to themed fallback instead of
                // bubbling Err so callers never see a bare unthemed <pre><code>.
                Err(_) => return Ok(fallback_lines(code, &slug)),
            };
            match styled_line_to_highlighted_html(&regions[..], IncludeBackground::No) {
                Ok(line_html) => lines.push(line_html),
                Err(_) => return Ok(fallback_lines(code, &slug)),
            }
        }

        Ok(HighlightedLines {
            theme_slug: slug,
            lines,
            fallback: false,
        })
    }

    /// Highlight a code block **twice** (a light theme and a dark theme) and
    /// emit per-token CSS *custom properties* (`--shiki-light` / `--shiki-dark`)
    /// instead of an inline `color:`.
    ///
    /// This is the engine primitive for dual-theme (light + dark) rendering: a
    /// single HTML payload carries both colours per token, and CSS picks which
    /// custom property to apply based on the active colour scheme. The variable
    /// names mirror Shiki's dual-theme convention so downstream CSS is familiar.
    ///
    /// * `code` - raw source code (no surrounding HTML).
    /// * `lang` - language identifier from the markdown fence.
    /// * `theme_light` / `theme_dark` - theme names; BOTH must resolve or the
    ///   call returns [`HighlightError::UnknownTheme`] (same path as the
    ///   single-theme method).
    ///
    /// Returns a [`DualHighlightedLines`] carrying:
    /// - `lines`: one HTML fragment per source line. On the highlighted path each
    ///   token is `<span style="--shiki-light:#…;--shiki-dark:#…">{escaped}</span>`.
    ///   On the fallback path each entry is the HTML-escaped source line with no
    ///   colour vars.
    /// - `light_bg` / `dark_bg`: each theme's background as `#rrggbb`, or `None`
    ///   when that theme defines no `settings.background` (colour-only `.tmTheme`).
    /// - `fallback`: `true` when the themed-fallback path was used (unknown lang,
    ///   tokenization error, or a per-line region-alignment mismatch).
    ///
    /// ## Region-alignment guard
    ///
    /// Tokenization is syntax/scope-driven, not theme-driven, so highlighting the
    /// same syntax under two themes yields region lists whose text slices
    /// concatenate to identical per-line text. This is *asserted* per line: on any
    /// mismatch the method degrades to the escaped fallback rather than zipping
    /// misaligned spans.
    pub fn highlight_lines_dual(
        &self,
        code: &str,
        lang: Option<&str>,
        theme_light: &str,
        theme_dark: &str,
    ) -> Result<DualHighlightedLines, HighlightError> {
        // Resolve BOTH themes up front, mirroring `highlight_lines`'
        // UnknownTheme path. Unknown lang degrades to fallback (not an error),
        // but an unknown theme name is always an error.
        let light_obj: &Theme = self
            .theme_set
            .themes
            .get(theme_light)
            .ok_or_else(|| HighlightError::UnknownTheme(theme_light.to_string()))?;
        let dark_obj: &Theme = self
            .theme_set
            .themes
            .get(theme_dark)
            .ok_or_else(|| HighlightError::UnknownTheme(theme_dark.to_string()))?;

        // Background vars are emitted whenever the theme defines one; a
        // colour-only theme (no `settings.background`) yields `None` and the
        // corresponding `--shiki-*-bg` var is simply omitted downstream.
        let light_bg = light_obj.settings.background.map(color_to_hex);
        let dark_bg = dark_obj.settings.background.map(color_to_hex);

        let syntax = self.resolve_syntax(lang);

        let Some(syntax) = syntax else {
            return Ok(dual_fallback_lines(code, light_bg, dark_bg));
        };

        // Two highlighters over the SAME resolved syntax — only the theme
        // differs, so per-line region *text* is identical between them.
        let mut h_light = HighlightLines::new(syntax, light_obj);
        let mut h_dark = HighlightLines::new(syntax, dark_obj);
        let mut lines: Vec<String> = Vec::new();
        for line in LinesWithEndings::from(code) {
            let light_regions = match h_light.highlight_line(line, &self.syntax_set) {
                Ok(r) => r,
                Err(_) => return Ok(dual_fallback_lines(code, light_bg, dark_bg)),
            };
            let dark_regions = match h_dark.highlight_line(line, &self.syntax_set) {
                Ok(r) => r,
                Err(_) => return Ok(dual_fallback_lines(code, light_bg, dark_bg)),
            };

            // Region-zip guard: the two themes must produce the same token
            // boundaries (same count, same text per token). If they don't, the
            // zip would emit misaligned spans — degrade to fallback instead.
            let aligned = light_regions.len() == dark_regions.len()
                && light_regions
                    .iter()
                    .zip(dark_regions.iter())
                    .all(|((_, lt), (_, dt))| lt == dt);
            if !aligned {
                return Ok(dual_fallback_lines(code, light_bg, dark_bg));
            }

            let mut line_html = String::new();
            for ((light_style, text), (dark_style, _)) in
                light_regions.iter().zip(dark_regions.iter())
            {
                // Spec (#1066): a dual span carries ONLY `--shiki-light` /
                // `--shiki-dark` color vars — the sole difference vs the single
                // path is those vars replacing `color:`. Syntect font styles
                // (bold/italic/underline) are intentionally NOT emitted here:
                // the two themes could disagree on style and there is no dual
                // custom-property convention for it in this primitive. Wiring
                // font styles is out of scope for this engine sub-issue.
                //
                // Escape with the SAME escaper syntect uses for text nodes so the
                // escaped output is byte-identical to the single path's token
                // text. (Verified equal to syntect's `Escape` in tests.)
                let escaped = escape_html(text);
                line_html.push_str("<span style=\"--shiki-light:");
                line_html.push_str(&color_to_hex(light_style.foreground));
                line_html.push_str(";--shiki-dark:");
                line_html.push_str(&color_to_hex(dark_style.foreground));
                line_html.push_str("\">");
                line_html.push_str(&escaped);
                line_html.push_str("</span>");
            }
            lines.push(line_html);
        }

        Ok(DualHighlightedLines {
            lines,
            light_bg,
            dark_bg,
            fallback: false,
        })
    }

    /// Highlight a code block in **class-emission mode** — every token is
    /// wrapped in a `<span class="…">` carrying a semantic *role* class (from
    /// the #1529 [`classify`] taxonomy) instead of an inline `color:` or a
    /// `--shiki-*` custom property. This is the engine primitive for
    /// `codeHighlight.mode: "class"` (Highlight Tokens epic, zfb#1528).
    ///
    /// Unlike [`Self::highlight_lines`] / [`Self::highlight_lines_dual`], this
    /// path does NOT go through syntect's `HighlightLines` (which applies a
    /// theme and discards the scope stack). Class mode needs the raw scopes,
    /// so it drives a `ParseState::parse_line` + `ScopeStack::apply` loop
    /// directly and classifies each token's scope stack.
    ///
    /// * `code` - raw source code (no surrounding HTML).
    /// * `lang` - language identifier from the markdown fence.
    /// * `prefix` - class-name prefix (e.g. `"hi-"`); the default class for a
    ///   role is `{prefix}{short_name}` (e.g. `hi-kw`).
    /// * `role_classes` - per-role class overrides keyed by the canonical full
    ///   role name (e.g. `"keyword"` → `"text-violet-600
    ///   dark:text-violet-400"`); when a role has an override its value is
    ///   emitted verbatim (attribute-escaped) instead of
    ///   `{prefix}{short_name}`.
    ///
    /// ## Cross-line scope state
    ///
    /// ONE `ParseState` and ONE `ScopeStack` are persisted across ALL lines of
    /// the block. A scope pushed on one line (an open block comment, a
    /// multi-line string, a template literal) is popped on a later line;
    /// resetting either per line would silently misclassify line 2+.
    ///
    /// ## Token emission
    ///
    /// Per token: [`classify`] the scope stack → resolved class is
    /// `role_classes[short_name]` if configured, else `{prefix}{short_name}`;
    /// emit `<span class="{escaped-class}">{escaped-text}</span>`. Adjacent
    /// tokens that resolve to the same class are MERGED into one span.
    /// Unclassified tokens (classifier returns `None`) are emitted as bare
    /// escaped text with NO wrapper span (they inherit the base foreground).
    ///
    /// ## Fallback
    ///
    /// Unknown lang or a parse/apply error mirrors [`fallback_lines`]:
    /// HTML-escaped source lines with no token spans (`fallback = true`).
    pub fn highlight_lines_classes(
        &self,
        code: &str,
        lang: Option<&str>,
        prefix: &str,
        role_classes: &BTreeMap<String, String>,
    ) -> Result<ClassHighlightedLines, HighlightError> {
        let syntax = self.resolve_syntax(lang);

        let Some(syntax) = syntax else {
            return Ok(class_fallback_lines(
                code,
                ClassHighlightFallbackReason::UnknownLanguage,
            ));
        };

        // ONE ParseState + ONE ScopeStack across ALL lines — cross-line
        // constructs (block comments, multi-line strings, template literals)
        // depend on the scope state surviving line boundaries.
        let mut state = ParseState::new(syntax);
        let mut stack = ScopeStack::new();
        let mut lines: Vec<String> = Vec::new();
        for line in LinesWithEndings::from(code) {
            let ops = match state.parse_line(line, &self.syntax_set) {
                Ok(ops) => ops,
                // Degrade to escaped fallback instead of bubbling Err so
                // callers never see a bare unclassified block.
                Err(_) => {
                    return Ok(class_fallback_lines(
                        code,
                        ClassHighlightFallbackReason::Tokenization,
                    ));
                }
            };
            // Per-line run buffer: consecutive tokens with the same resolved
            // class are merged into a single span. A run's class is
            // `Some(class)` for a classified token, `None` for an
            // unclassified (bare-text) run.
            let mut runs: Vec<(Option<String>, String)> = Vec::new();
            for (tok, op) in ScopeRegionIterator::new(&ops, line) {
                if stack.apply(op).is_err() {
                    return Ok(class_fallback_lines(
                        code,
                        ClassHighlightFallbackReason::Tokenization,
                    ));
                }
                if tok.is_empty() {
                    continue;
                }
                let resolved = classify(stack.as_slice()).map(|role| {
                    // `roleClasses` overrides are keyed by the FULL role name
                    // (`"keyword"`), matching user config / `CODE_HIGHLIGHT_ROLES`.
                    // The default class uses the short suffix (`hi-kw`). Looking
                    // the override up by `short_name` would silently miss every
                    // full-name key (zfb#1528 deep-review fix).
                    role_classes
                        .get(role.full_name())
                        .cloned()
                        .unwrap_or_else(|| format!("{prefix}{}", role.short_name()))
                });
                let escaped = escape_html(tok);
                match runs.last_mut() {
                    Some((cls, text)) if *cls == resolved => text.push_str(&escaped),
                    _ => runs.push((resolved, escaped)),
                }
            }
            let mut line_html = String::new();
            for (cls, text) in runs {
                match cls {
                    Some(class) => {
                        line_html.push_str("<span class=\"");
                        line_html.push_str(&escape_html(&class));
                        line_html.push_str("\">");
                        line_html.push_str(&text);
                        line_html.push_str("</span>");
                    }
                    None => line_html.push_str(&text),
                }
            }
            lines.push(line_html);
        }

        Ok(ClassHighlightedLines {
            lines,
            fallback: false,
            fallback_reason: None,
        })
    }

    /// Render arbitrary source in semantic class mode without constructing a
    /// Markdown fence.
    ///
    /// This is the shared facade for direct consumers and the native Markdown
    /// class-mode plugin. It validates the direct-call options, calls
    /// [`Self::highlight_lines_classes`] exactly once, then owns the canonical
    /// `<pre> → <code> → <span class="line">` wrapper markup. Unknown
    /// languages and tokenizer failures are successful, escaped fallback
    /// outcomes whose typed reason is exposed on [`ClassHighlightOutcome`].
    pub fn render_class_highlight(
        &self,
        code: &str,
        language: &str,
        class_prefix: &str,
        role_classes: &BTreeMap<String, String>,
    ) -> Result<ClassHighlightOutcome, ClassHighlightRenderError> {
        validate_class_highlight_options(language, class_prefix, role_classes)
            .map_err(ClassHighlightRenderError::Validation)?;

        let highlighted = self
            .highlight_lines_classes(code, Some(language), class_prefix, role_classes)
            .map_err(ClassHighlightRenderError::Highlight)?;
        let root_class = format!("{class_prefix}root");
        let html = render_class_highlight_markup(&root_class, &highlighted.lines);

        Ok(ClassHighlightOutcome {
            html,
            fallback_reason: highlighted.fallback_reason,
            root_class,
            lines: highlighted.lines,
        })
    }
}

/// Per-line highlighting result returned by [`Highlighter::highlight_lines`].
#[derive(Debug, Clone)]
pub struct HighlightedLines {
    /// CSS-safe theme slug (used as `syntect-{slug}` class on `<pre>`).
    pub theme_slug: String,
    /// One HTML fragment per source line from syntect.
    /// On the fallback path each entry is the HTML-escaped source line.
    pub lines: Vec<String>,
    /// `true` when the output used the themed-fallback path (unknown lang or
    /// tokenization error) rather than per-token syntect highlighting.
    pub fallback: bool,
}

/// Per-line dual-theme highlighting result returned by
/// [`Highlighter::highlight_lines_dual`].
///
/// Each token carries both a light and a dark colour as CSS custom properties
/// (`--shiki-light` / `--shiki-dark`) so a single payload renders correctly
/// under either colour scheme. The two `*_bg` fields are the per-theme
/// backgrounds (each `Option`: `None` when a theme defines no background).
#[derive(Debug, Clone)]
pub struct DualHighlightedLines {
    /// One HTML fragment per source line. On the highlighted path each token is
    /// `<span style="--shiki-light:#…;--shiki-dark:#…">{escaped}</span>`; on the
    /// fallback path each entry is the HTML-escaped source line (no colour vars).
    pub lines: Vec<String>,
    /// Light theme background as `#rrggbb`, or `None` when the theme defines no
    /// `settings.background` (the `--shiki-light-bg` var is then omitted).
    pub light_bg: Option<String>,
    /// Dark theme background as `#rrggbb`, or `None` when the theme defines no
    /// `settings.background` (the `--shiki-dark-bg` var is then omitted).
    pub dark_bg: Option<String>,
    /// `true` when the output used the themed-fallback path (unknown lang,
    /// tokenization error, or a per-line region-alignment mismatch) rather than
    /// per-token dual highlighting.
    pub fallback: bool,
}

/// Per-line class-mode highlighting result returned by
/// [`Highlighter::highlight_lines_classes`].
///
/// Each token is `<span class="…">{escaped}</span>` carrying a semantic role
/// class (or bare escaped text for unclassified tokens). Unlike
/// [`HighlightedLines`] there is no `theme_slug`: class mode is theme-agnostic
/// (colours come from the consumer's CSS keyed on the role classes), and the
/// `<pre>` wrapper is classed `{prefix}root` by the plugin, not `syntect-{slug}`.
#[derive(Debug, Clone)]
pub struct ClassHighlightedLines {
    /// One HTML fragment per source line. On the highlighted path each token is
    /// a role-classed `<span>` (adjacent same-class tokens merged) or bare
    /// escaped text; on the fallback path each entry is the HTML-escaped source
    /// line with no spans.
    pub lines: Vec<String>,
    /// `true` when the output used the escaped-fallback path (unknown lang or a
    /// parse/apply error) rather than per-token class highlighting.
    pub fallback: bool,
    /// The exact escaped-fallback cause, when [`Self::fallback`] is true.
    ///
    /// This supplements the legacy boolean so direct consumers can distinguish
    /// an unsupported language from a tokenizer failure without attempting to
    /// inspect the generated HTML.
    pub fallback_reason: Option<ClassHighlightFallbackReason>,
}

/// Why a class-highlight operation produced escaped source instead of role
/// spans. These are expected outcomes, not traps or validation errors.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ClassHighlightFallbackReason {
    /// No bundled syntax or supported alias matched the supplied non-empty
    /// language token.
    UnknownLanguage,
    /// Syntect could not parse a line or apply its scope operations.
    Tokenization,
}

/// Result of [`Highlighter::render_class_highlight`].
///
/// `html` is the ready-to-emit semantic wrapper used by direct consumers. The
/// native Markdown plugin uses the crate-private line and root-class accessors
/// to preserve its structured HAST nodes for downstream code enrichment while
/// sharing this renderer's tokenization, validation, fallback, and wrapper
/// contract.
#[derive(Debug, Clone)]
pub struct ClassHighlightOutcome {
    /// Complete escaped HTML:
    /// `<pre class="{prefix}root"><code><span class="line">…`.
    pub html: String,
    /// `None` for tokenized output; otherwise the expected fallback cause.
    pub fallback_reason: Option<ClassHighlightFallbackReason>,
    root_class: String,
    lines: Vec<String>,
}

impl ClassHighlightOutcome {
    /// Root `<pre>` class for the native structured-HAST adapter.
    #[must_use]
    pub(crate) fn root_class(&self) -> &str {
        &self.root_class
    }

    /// Per-source-line HTML fragments for the native structured-HAST adapter.
    #[must_use]
    pub(crate) fn into_lines(self) -> Vec<String> {
        self.lines
    }
}

/// Invalid direct class-highlight options.
///
/// Native `zfb` config prefixes these field-oriented messages with
/// `codeHighlight.` while retaining theme mutual-exclusion and Tailwind policy
/// validation in its own layer.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ClassHighlightValidationError {
    /// The direct facade requires a language; Markdown blocks without a
    /// language remain outside the syntect plugin as before.
    EmptyLanguage,
    /// The prefix would not be a valid semantic class-name prefix.
    InvalidClassPrefix { prefix: String },
    /// A role override did not use a canonical full role name.
    UnknownRole { role: String },
    /// An override would collide with the Markdown line-wrapper class.
    LineClassCollision { role: String, class: String },
}

impl std::fmt::Display for ClassHighlightValidationError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::EmptyLanguage => write!(f, "language must be non-empty"),
            Self::InvalidClassPrefix { prefix } => write!(
                f,
                "classPrefix {prefix:?} must be non-empty and match /^[A-Za-z][A-Za-z0-9_-]*$/"
            ),
            Self::UnknownRole { role } => write!(
                f,
                "roleClasses key {role:?} is not a known role; valid roles are: {}",
                crate::hi_roles::HiRole::FULL_NAMES.join(", ")
            ),
            Self::LineClassCollision { role, class } => write!(
                f,
                "roleClasses[{role:?}] value {class:?} must not contain the token \"line\" (collides with the code-enrichment line wrapper class)"
            ),
        }
    }
}

impl std::error::Error for ClassHighlightValidationError {}

/// Error from [`Highlighter::render_class_highlight`].
#[derive(Debug, thiserror::Error)]
pub enum ClassHighlightRenderError {
    /// The caller supplied invalid class-highlight options.
    #[error(transparent)]
    Validation(#[from] ClassHighlightValidationError),
    /// An unexpected highlighter-level error. Normal unknown-language and
    /// tokenization cases are represented by [`ClassHighlightOutcome`], not
    /// this error.
    #[error(transparent)]
    Highlight(#[from] HighlightError),
}

/// Validate class-prefix and role-override values shared by native config and
/// the direct arbitrary-code facade.
pub fn validate_class_highlight_classes(
    class_prefix: &str,
    role_classes: &BTreeMap<String, String>,
) -> Result<(), ClassHighlightValidationError> {
    if !is_valid_class_prefix(class_prefix) {
        return Err(ClassHighlightValidationError::InvalidClassPrefix {
            prefix: class_prefix.to_string(),
        });
    }
    for key in role_classes.keys() {
        if !crate::hi_roles::HiRole::FULL_NAMES.contains(&key.as_str()) {
            return Err(ClassHighlightValidationError::UnknownRole { role: key.clone() });
        }
    }
    for (role, class) in role_classes {
        if class.split_whitespace().any(|token| token == "line") {
            return Err(ClassHighlightValidationError::LineClassCollision {
                role: role.clone(),
                class: class.clone(),
            });
        }
    }
    Ok(())
}

/// Validate direct arbitrary-code class-highlight options.
///
/// Unlike fenced Markdown, a direct call has no meaningful no-language mode,
/// so an empty language is rejected instead of being silently treated as
/// unhighlighted text.
pub fn validate_class_highlight_options(
    language: &str,
    class_prefix: &str,
    role_classes: &BTreeMap<String, String>,
) -> Result<(), ClassHighlightValidationError> {
    if language.is_empty() {
        return Err(ClassHighlightValidationError::EmptyLanguage);
    }
    validate_class_highlight_classes(class_prefix, role_classes)
}

