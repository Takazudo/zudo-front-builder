//! Regression tests for #3002 (Plugin Alias In Node Modules epic #3014,
//! sub-issue #3018) on the page/layout SSR bundler: a route entrypoint whose
//! realpath is **under `node_modules`** must be able to `import` a
//! plugin-registered `ctx.addAlias` specifier whose target is a single
//! existing file.
//!
//! Same gap as `bundler_node_modules_virtual_module.rs` (#1263): esbuild does
//! not apply the synthetic tsconfig's `compilerOptions.paths` to a source file
//! whose directory `isInsideNodeModules`, so the alias also rides an esbuild
//! `--alias` flag. The SSR pass adds a gate the islands pass does not need:
//! the flag is emitted from the shadow-remapped `effective_plugin_aliases`
//! only when that target lies inside the stage root, so it can never point
//! esbuild at the live tree and trip the #1706 stage-escape audit.
//!
//! Every test drives a real esbuild through a wrapper script that records its
//! argv and keeps a copy of the metafile, because the shadow holding the
//! original is dropped once `bundle` returns.

#![cfg(unix)]

use std::collections::BTreeMap;
use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};

use zfb_build::{bundle, BundleMode, BundlerInput};
use zfb_render::adapters::Framework;
use zfb_test_utils::locate_esbuild;

/// A non-matching pattern: activates `bundle.exclude` (and with it the
/// unconditional shadow remap of every alias target) without excluding
/// anything the fixture imports.
const INERT_EXCLUDE: &str = "never-matches/**";

struct Recorder {
    wrapper: PathBuf,
    argv_log: PathBuf,
    metafile_copy: PathBuf,
}

impl Recorder {
    fn new(dir: &Path, esbuild: &Path) -> Self {
        fs::create_dir_all(dir).unwrap();
        let wrapper = dir.join("esbuild-recorder.sh");
        let argv_log = dir.join("argv.log");
        let metafile_copy = dir.join("metafile.json");
        let quote = |p: &Path| format!("'{}'", p.display());
        fs::write(
            &wrapper,
            format!(
                "#!/bin/sh\n\
                 : > {log}\n\
                 for arg in \"$@\"; do printf '%s\\n' \"$arg\" >> {log}; done\n\
                 {esbuild} \"$@\"\n\
                 status=$?\n\
                 for arg in \"$@\"; do\n\
                   case \"$arg\" in\n\
                     --metafile=*) cp \"${{arg#--metafile=}}\" {meta} 2>/dev/null ;;\n\
                   esac\n\
                 done\n\
                 exit \"$status\"\n",
                log = quote(&argv_log),
                esbuild = quote(esbuild),
                meta = quote(&metafile_copy),
            ),
        )
        .unwrap();
        fs::set_permissions(&wrapper, fs::Permissions::from_mode(0o755)).unwrap();
        Self {
            wrapper,
            argv_log,
            metafile_copy,
        }
    }

    fn argv(&self) -> Vec<String> {
        fs::read_to_string(&self.argv_log)
            .expect("esbuild was invoked")
            .lines()
            .map(str::to_owned)
            .collect()
    }

    fn alias_flags_for(&self, from: &str) -> Vec<String> {
        let prefix = format!("--alias:{from}=");
        self.argv()
            .into_iter()
            .filter(|arg| arg.starts_with(&prefix))
            .collect()
    }

    fn metafile_input_keys(&self) -> Vec<String> {
        let bytes = fs::read(&self.metafile_copy).expect("read metafile copy");
        let value: serde_json::Value = serde_json::from_slice(&bytes).expect("parse metafile");
        value["inputs"]
            .as_object()
            .expect("metafile inputs object")
            .keys()
            .cloned()
            .collect()
    }
}

/// The #1263 fixture shape: a *published* preset whose route entrypoint is a
/// REAL directory under `node_modules` (a symlink would be canonicalised out
/// of it), pulled into the graph by the host page.
fn write_project(root: &Path, entrypoint_source: &str) {
    for d in ["pages", "components", "layouts", "content", "src"] {
        fs::create_dir_all(root.join(d)).unwrap();
    }
    let pkg_routes = root.join("node_modules/@scope/preset/dist/routes");
    fs::create_dir_all(&pkg_routes).unwrap();
    fs::write(
        root.join("node_modules/@scope/preset/package.json"),
        r#"{ "name": "@scope/preset", "version": "0.0.0" }"#,
    )
    .unwrap();
    fs::write(pkg_routes.join("_chrome.tsx"), entrypoint_source).unwrap();
    fs::write(
        root.join("pages/index.tsx"),
        r#"
            import { Chrome } from "@scope/preset/dist/routes/_chrome";
            export default function Home() {
              return Chrome();
            }
        "#,
    )
    .unwrap();
}

fn write_file_target(path: &Path, marker: &str) {
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, format!("export default \"{marker}\";\n")).unwrap();
}

fn base_input(root: &Path, recorder: &Recorder) -> BundlerInput {
    let mut input = BundlerInput::for_project(
        root.to_path_buf(),
        Framework::Preact,
        BundleMode::Production,
        root.join(".zfb-build"),
        None,
    );
    input.external = vec![
        "preact".into(),
        "preact-render-to-string".into(),
        "@takazudo/zfb-runtime".into(),
    ];
    input.esbuild_binary = Some(recorder.wrapper.clone());
    input.node_modules_dir = Some(root.join("node_modules"));
    // A non-empty user mapping pins the same production-shaped esbuild branch
    // as the #1263 sibling test. Its key must not claim `@/…`: a user-claimed
    // specifier gets no flag (user-wins, #1267).
    let src_glob = root.join("src").join("*").to_string_lossy().into_owned();
    input.tsconfig_paths = BTreeMap::from([("#inert/*".to_string(), vec![src_glob])]);
    input
}

macro_rules! esbuild_or_skip {
    () => {
        match locate_esbuild() {
            Some(esbuild) => esbuild,
            None => {
                eprintln!(
                    "[bundler_node_modules_plugin_alias] no esbuild binary available; skipping."
                );
                return;
            }
        }
    };
}

/// **Primary #3002 gate — build bundler, exclusions active.** The
/// node_modules entrypoint resolves the single-file alias `@/stub`; the flag
/// points at the STAGED spelling and the metafile records the staged input.
#[test]
fn plugin_alias_resolves_from_node_modules_route_entrypoint_via_staged_flag() {
    let esbuild = esbuild_or_skip!();
    let tmp = tempfile::tempdir().expect("tempdir");
    let root = tmp.path().join("project");
    let recorder = Recorder::new(&tmp.path().join("recorder"), &esbuild);
    write_project(
        &root,
        r#"
            import marker from "@/stub";
            export function Chrome() {
              return "chrome:" + marker;
            }
        "#,
    );
    let target = root.join("src/stub.ts");
    write_file_target(&target, "NodeModulesPluginAliasMarker");

    let mut input = base_input(&root, &recorder);
    input.bundle_exclude = vec![INERT_EXCLUDE.to_string()];
    input.plugin_alias_entries =
        vec![("@/stub".to_string(), target.to_string_lossy().into_owned())];

    let out = bundle(input).expect(
        "#3002: a route entrypoint whose realpath is under node_modules must resolve a \
         registered single-file plugin alias; the tsconfig is not applied there, so the \
         `--alias` flag must be",
    );
    let body = fs::read_to_string(&out.bundle_path).expect("read bundle");
    assert!(
        body.contains("NodeModulesPluginAliasMarker"),
        "the aliased target must reach the bundle; got:\n{body}"
    );

    let flags = recorder.alias_flags_for("@/stub");
    assert_eq!(flags.len(), 1, "exactly one `@/stub` flag; got {flags:?}");
    let flag_target = flags[0].trim_start_matches("--alias:@/stub=");
    assert!(
        flag_target.ends_with("/src/stub.ts") && !Path::new(flag_target).starts_with(&root),
        "the flag must point at the staged copy, never the live tree; got {flag_target}"
    );

    let keys = recorder.metafile_input_keys();
    assert!(
        keys.iter().any(|k| k == "src/stub.ts"),
        "metafile inputs must record the EXACT staged spelling `src/stub.ts`; got {keys:?}"
    );
}

/// **Negative twin (#269 exact-match contract).** `@/stub/deeper` must not
/// resolve through the single-file flag (`<stub.ts>/deeper` has no file).
/// Asserts the failure itself, not esbuild's message text.
#[test]
fn plugin_alias_prefix_with_slash_still_fails_from_node_modules_route_entrypoint() {
    let esbuild = esbuild_or_skip!();
    let tmp = tempfile::tempdir().expect("tempdir");
    let root = tmp.path().join("project");
    let recorder = Recorder::new(&tmp.path().join("recorder"), &esbuild);
    write_project(
        &root,
        r#"
            import marker from "@/stub/deeper";
            export function Chrome() {
              return "chrome:" + marker;
            }
        "#,
    );
    let target = root.join("src/stub.ts");
    write_file_target(&target, "NodeModulesPluginAliasMarker");

    let mut input = base_input(&root, &recorder);
    input.bundle_exclude = vec![INERT_EXCLUDE.to_string()];
    input.plugin_alias_entries =
        vec![("@/stub".to_string(), target.to_string_lossy().into_owned())];

    bundle(input).expect_err(
        "#269 + #3002: single-file alias `@/stub` must NOT match `@/stub/deeper`, even via \
         the node_modules `--alias` flag",
    );
    assert_eq!(
        recorder.alias_flags_for("@/stub").len(),
        1,
        "the failure must come from the exact-match contract, not a missing flag"
    );
}

/// **Empty `bundle.exclude`, target with no shadow copy → no flag.** An
/// out-of-project target is never staged, so `effective_plugin_aliases` falls
/// through to the live path; emitting a flag there would let esbuild read live
/// source. The alias stays tsconfig-only and still resolves for an ordinary
/// (non-node_modules) importer, exactly as before #3002.
#[test]
fn live_tree_alias_target_under_empty_exclude_gets_no_flag() {
    let esbuild = esbuild_or_skip!();
    let tmp = tempfile::tempdir().expect("tempdir");
    let root = tmp.path().join("project");
    let recorder = Recorder::new(&tmp.path().join("recorder"), &esbuild);
    write_project(&root, "export function Chrome() { return \"chrome\"; }\n");
    fs::write(
        root.join("pages/index.tsx"),
        r#"
            import marker from "@/outside";
            export default function Home() {
              return marker;
            }
        "#,
    )
    .unwrap();
    let target = tmp.path().join("elsewhere/outside.ts");
    write_file_target(&target, "LiveTreeAliasMarker");

    let mut input = base_input(&root, &recorder);
    input.plugin_alias_entries = vec![(
        "@/outside".to_string(),
        target.to_string_lossy().into_owned(),
    )];

    let out = bundle(input).expect("the tsconfig-only alias must still resolve");
    let body = fs::read_to_string(&out.bundle_path).expect("read bundle");
    assert!(
        body.contains("LiveTreeAliasMarker"),
        "the alias must still resolve through the tsconfig; got:\n{body}"
    );
    assert!(
        target.is_file(),
        "precondition: the target is a file, so only the stage gate withholds the flag"
    );
    assert_eq!(
        recorder.alias_flags_for("@/outside"),
        Vec::<String>::new(),
        "a target outside the stage root must not become an `--alias` flag"
    );
}

/// **`zfb` is reserved.** The SSR pass hardcodes `--alias:zfb=@takazudo/zfb`,
/// so a plugin alias named `zfb` or `zfb/x` gets no flag (and a warning) even
/// with a staged file target that would otherwise qualify.
#[test]
fn plugin_alias_named_zfb_gets_no_flag() {
    let esbuild = esbuild_or_skip!();
    let tmp = tempfile::tempdir().expect("tempdir");
    let root = tmp.path().join("project");
    let recorder = Recorder::new(&tmp.path().join("recorder"), &esbuild);
    write_project(&root, "export function Chrome() { return \"chrome\"; }\n");
    let zfb_target = root.join("src/zfb-shadow.ts");
    let zfb_sub_target = root.join("src/zfb-sub.ts");
    write_file_target(&zfb_target, "ZfbReserved");
    write_file_target(&zfb_sub_target, "ZfbSubReserved");

    let mut input = base_input(&root, &recorder);
    input.bundle_exclude = vec![INERT_EXCLUDE.to_string()];
    input.plugin_alias_entries = vec![
        ("zfb".to_string(), zfb_target.to_string_lossy().into_owned()),
        (
            "zfb/x".to_string(),
            zfb_sub_target.to_string_lossy().into_owned(),
        ),
    ];

    bundle(input).expect("a build that never imports the reserved aliases must succeed");
    assert_eq!(
        recorder.alias_flags_for("zfb"),
        vec!["--alias:zfb=@takazudo/zfb".to_string()],
        "only the hardcoded `zfb` alias may reach argv"
    );
    assert_eq!(
        recorder.alias_flags_for("zfb/x"),
        Vec::<String>::new(),
        "`zfb/x` collides with the reserved `zfb` prefix and must not become a flag"
    );
}
