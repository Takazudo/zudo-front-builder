//! Regression tests for #3002 (Plugin Alias In Node Modules epic #3014,
//! sub-issue #3018) on the page/layout SSR bundler: a route entrypoint whose
//! realpath is **under `node_modules`** must be able to `import` a
//! plugin-registered `ctx.addAlias` specifier whose target is a single
//! existing file.
//!
//! Same gap as `bundler_node_modules_virtual_module.rs` (#1263): the
//! synthetic tsconfig's `compilerOptions.paths` does not apply to a source
//! file under `node_modules`, so the alias also rides a resolver alias. The
//! SSR pass adds a gate the islands pass does not need: the alias is emitted
//! from the shadow-remapped `effective_plugin_aliases` only when that target
//! lies inside the stage root, so it can never point the bundler at the live
//! tree and trip the #1706 stage-escape audit. The emitted aliases themselves
//! are pinned by the `ssr_bundle_request` unit tests in `bundler.rs`; these
//! tests prove the resolution behavior end to end.

#![cfg(unix)]

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use zfb_build::{bundle, BundleMode, BundlerInput};

/// A non-matching pattern: activates `bundle.exclude` (and with it the
/// unconditional shadow remap of every alias target) without excluding
/// anything the fixture imports.
const INERT_EXCLUDE: &str = "never-matches/**";

/// The #1263 fixture shape: a *published* preset whose route entrypoint is a
/// REAL directory under `node_modules` (a symlink would be canonicalised out
/// of it), pulled into the graph by the host page.
fn write_project(root: &Path, entrypoint_source: &str) {
    for d in ["pages", "components", "layouts", "content", "src"] {
        fs::create_dir_all(root.join(d)).unwrap();
    }
    let pkg_routes = root.join("node_modules/@scope/preset/dist/routes");
    fs::create_dir_all(&pkg_routes).unwrap();
    fs::write(
        root.join("node_modules/@scope/preset/package.json"),
        r#"{ "name": "@scope/preset", "version": "0.0.0" }"#,
    )
    .unwrap();
    fs::write(pkg_routes.join("_chrome.tsx"), entrypoint_source).unwrap();
    fs::write(
        root.join("pages/index.tsx"),
        r#"
            import { Chrome } from "@scope/preset/dist/routes/_chrome";
            export default function Home() {
              return Chrome();
            }
        "#,
    )
    .unwrap();
}

fn write_file_target(path: &Path, marker: &str) {
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, format!("export default \"{marker}\";\n")).unwrap();
}

fn base_input(root: &Path) -> BundlerInput {
    let mut input = BundlerInput::for_project(
        root.to_path_buf(),
        BundleMode::Production,
        root.join(".zfb-build"),
        None,
    );
    input.zudo_react_island_names = Some(vec![]);
    input.external = vec![
        "@takazudo/zfb/zudo-react".into(),
        "@takazudo/zfb-runtime".into(),
    ];
    input.node_modules_dir = Some(root.join("node_modules"));
    // A non-empty user mapping pins the same production-shaped bundler branch
    // as the #1263 sibling test. Its key must not claim `@/…`: a user-claimed
    // specifier gets no flag (user-wins, #1267).
    let src_glob = root.join("src").join("*").to_string_lossy().into_owned();
    input.tsconfig_paths = BTreeMap::from([("#inert/*".to_string(), vec![src_glob])]);
    input
}

/// **Primary #3002 gate — build bundler, exclusions active.** The
/// node_modules entrypoint resolves the single-file alias `@/stub`.
#[test]
fn plugin_alias_resolves_from_node_modules_route_entrypoint_via_staged_flag() {
    let tmp = tempfile::tempdir().expect("tempdir");
    let root = tmp.path().join("project");
    write_project(
        &root,
        r#"
            import marker from "@/stub";
            export function Chrome() {
              return "chrome:" + marker;
            }
        "#,
    );
    let target = root.join("src/stub.ts");
    write_file_target(&target, "NodeModulesPluginAliasMarker");

    let mut input = base_input(&root);
    input.bundle_exclude = vec![INERT_EXCLUDE.to_string()];
    input.plugin_alias_entries =
        vec![("@/stub".to_string(), target.to_string_lossy().into_owned())];

    let out = bundle(input).expect(
        "#3002: a route entrypoint whose realpath is under node_modules must resolve a \
         registered single-file plugin alias; the tsconfig is not applied there, so the \
         resolver alias must be",
    );
    let body = fs::read_to_string(&out.bundle_path).expect("read bundle");
    assert!(
        body.contains("NodeModulesPluginAliasMarker"),
        "the aliased target must reach the bundle; got:\n{body}"
    );
}

/// **Negative twin (#269 exact-match contract).** `@/stub/deeper` must not
/// resolve through the single-file alias (`<stub.ts>/deeper` has no file).
/// Asserts the failure itself, not the bundler's message text.
#[test]
fn plugin_alias_prefix_with_slash_still_fails_from_node_modules_route_entrypoint() {
    let tmp = tempfile::tempdir().expect("tempdir");
    let root = tmp.path().join("project");
    write_project(
        &root,
        r#"
            import marker from "@/stub/deeper";
            export function Chrome() {
              return "chrome:" + marker;
            }
        "#,
    );
    let target = root.join("src/stub.ts");
    write_file_target(&target, "NodeModulesPluginAliasMarker");

    let mut input = base_input(&root);
    input.bundle_exclude = vec![INERT_EXCLUDE.to_string()];
    input.plugin_alias_entries =
        vec![("@/stub".to_string(), target.to_string_lossy().into_owned())];

    bundle(input).expect_err(
        "#269 + #3002: single-file alias `@/stub` must NOT match `@/stub/deeper`, even via \
         the node_modules resolver alias",
    );
}

/// **Empty `bundle.exclude`, target with no shadow copy → no alias.** An
/// out-of-project target is never staged, so `effective_plugin_aliases` falls
/// through to the live path; emitting a resolver alias there would let the
/// bundler read live source. The alias stays tsconfig-only and still resolves
/// for an ordinary (non-node_modules) importer, exactly as before #3002.
#[test]
fn live_tree_alias_target_under_empty_exclude_gets_no_flag() {
    let tmp = tempfile::tempdir().expect("tempdir");
    let root = tmp.path().join("project");
    write_project(&root, "export function Chrome() { return \"chrome\"; }\n");
    fs::write(
        root.join("pages/index.tsx"),
        r#"
            import marker from "@/outside";
            export default function Home() {
              return marker;
            }
        "#,
    )
    .unwrap();
    let target = tmp.path().join("elsewhere/outside.ts");
    write_file_target(&target, "LiveTreeAliasMarker");

    let mut input = base_input(&root);
    input.plugin_alias_entries = vec![(
        "@/outside".to_string(),
        target.to_string_lossy().into_owned(),
    )];

    let out = bundle(input).expect("the tsconfig-only alias must still resolve");
    let body = fs::read_to_string(&out.bundle_path).expect("read bundle");
    assert!(
        body.contains("LiveTreeAliasMarker"),
        "the alias must still resolve through the tsconfig; got:\n{body}"
    );
    assert!(
        target.is_file(),
        "precondition: the target is a file, so only the stage gate withholds the alias"
    );
}

/// **`zfb` is reserved.** The SSR pass hardcodes the `zfb` ->
/// `@takazudo/zfb` alias, so a plugin alias named `zfb` or `zfb/x` gets no
/// resolver alias (and a warning) even with a staged file target that would
/// otherwise qualify.
#[test]
fn plugin_alias_named_zfb_gets_no_flag() {
    let tmp = tempfile::tempdir().expect("tempdir");
    let root = tmp.path().join("project");
    write_project(&root, "export function Chrome() { return \"chrome\"; }\n");
    let zfb_target = root.join("src/zfb-shadow.ts");
    let zfb_sub_target = root.join("src/zfb-sub.ts");
    write_file_target(&zfb_target, "ZfbReserved");
    write_file_target(&zfb_sub_target, "ZfbSubReserved");

    let mut input = base_input(&root);
    input.bundle_exclude = vec![INERT_EXCLUDE.to_string()];
    input.plugin_alias_entries = vec![
        ("zfb".to_string(), zfb_target.to_string_lossy().into_owned()),
        (
            "zfb/x".to_string(),
            zfb_sub_target.to_string_lossy().into_owned(),
        ),
    ];

    bundle(input).expect("a build that never imports the reserved aliases must succeed");
}
