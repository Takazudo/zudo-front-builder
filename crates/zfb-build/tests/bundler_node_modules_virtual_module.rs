//! Regression test for #1263 (supersedes #1258) on the page/layout
//! bundler: a route entrypoint whose realpath is **under `node_modules`**
//! must be able to `import` a plugin-registered `virtual:*` module.
//!
//! ## Why this differs from the #443 workspace-package test
//!
//! `bundler_workspace_pkg_alias.rs` covers a pnpm *workspace* package
//! symlinked into `node_modules` whose canonical target is OUTSIDE
//! `node_modules` (`<tmp>/packages/foo`). esbuild canonicalises the
//! symlink and walks up from a non-`node_modules` path, so the synthetic
//! tsconfig's `compilerOptions.paths` DOES apply there.
//!
//! #1263 is the other case: a *published* package whose realpath stays
//! under `node_modules` (the common npm/pnpm-store layout). esbuild's
//! resolver refuses to apply `compilerOptions.paths` to any source file
//! whose directory `isInsideNodeModules` — `tsConfigForDir` returns `nil`
//! before it ever consults the `--tsconfig` override. So a preset that
//! registers `injectRoute` with an entrypoint at
//! `node_modules/@takazudo/zudo-doc/dist/routes/_chrome.js` importing
//! `virtual:foo` failed to bundle with
//! `Could not resolve "virtual:foo"`.
//!
//! The build bundler shares the gap because
//! `synthesize_static_overlay_module()` pulls the package entrypoint into
//! the graph by absolute path. The fix emits each virtual module ALSO as
//! an esbuild `--alias:<spec>=<tmp.mjs>` flag (not node_modules-gated),
//! exact-match-safe because the target is a single `.mjs` file.

use std::collections::BTreeMap;
use std::fs;

use zfb_build::{bundle, BundleMode, BundlerInput};
use zfb_render::adapters::Framework;
use zfb_test_utils::locate_esbuild;

/// **Primary #1263 gate — build bundler.**
#[test]
fn virtual_module_resolves_from_node_modules_route_entrypoint() {
    let Some(esbuild) = locate_esbuild() else {
        eprintln!(
            "[bundler_node_modules_virtual_module] no esbuild binary available; \
             set ZFB_ESBUILD_BIN, place the binary at \
             crates/zfb/binaries/esbuild/esbuild, or install esbuild on PATH. Skipping."
        );
        return;
    };

    let tmp = tempfile::tempdir().expect("tempdir");
    let root = tmp.path().to_path_buf();

    for d in ["pages", "components", "layouts", "content", "src"] {
        fs::create_dir_all(root.join(d)).unwrap();
    }

    // A *published* preset package whose route entrypoint physically lives
    // under `node_modules` (real directory, not a symlink to outside) — so
    // its realpath stays under `node_modules`, exactly the #1263 shape.
    let pkg_routes = root.join("node_modules/@scope/preset/dist/routes");
    fs::create_dir_all(&pkg_routes).unwrap();
    fs::write(
        root.join("node_modules/@scope/preset/package.json"),
        r#"{ "name": "@scope/preset", "version": "0.0.0" }"#,
    )
    .unwrap();
    // The node_modules-resident entrypoint imports the registered virtual
    // module. On `main` this is where bundling fails.
    fs::write(
        pkg_routes.join("_chrome.tsx"),
        r#"
            import marker from "virtual:foo";
            export function Chrome() {
              return "chrome:" + marker;
            }
        "#,
    )
    .unwrap();

    // Host page pulls the node_modules entrypoint into the graph.
    fs::write(
        root.join("pages/index.tsx"),
        r#"
            import { Chrome } from "@scope/preset/dist/routes/_chrome";
            export default function Home() {
              return Chrome();
            }
        "#,
    )
    .unwrap();

    let mut input = BundlerInput::for_project(
        root.clone(),
        Framework::Preact,
        BundleMode::Production,
        root.join(".zfb-build"),
        None,
    );
    input.external = vec![
        "preact".into(),
        "preact-render-to-string".into(),
        "@takazudo/zfb-runtime".into(),
    ];
    input.esbuild_binary = Some(esbuild);
    // Mirror production wiring (`commands/build.rs`): point esbuild at the
    // project's own node_modules so `@scope/preset` resolves.
    input.node_modules_dir = Some(root.join("node_modules"));
    // A non-empty `tsconfig_paths` puts the bundler on the SAME esbuild
    // invocation branch as the proven #443 workspace-package test
    // (`--preserve-symlinks` off + copy-mode shadow). The `@/*` mapping
    // itself is inert here — nothing imports it — but it pins the branch so
    // this test exercises the realistic production path. esbuild then
    // canonicalises the node_modules package to its real path under
    // `node_modules`, where `compilerOptions.paths` does not apply.
    let src_glob = root.join("src").join("*").to_string_lossy().into_owned();
    let mut tsconfig_paths = BTreeMap::new();
    tsconfig_paths.insert("@/*".to_string(), vec![src_glob]);
    input.tsconfig_paths = tsconfig_paths;
    // The plugin registration the preset would make via `addVirtualModule`.
    input.plugin_virtual_modules = vec![(
        "virtual:foo".to_string(),
        "export default \"NodeModulesVirtualMarker\";\n".to_string(),
    )];

    let out = bundle(input).expect(
        "#1263: a route entrypoint whose realpath is under node_modules must \
         resolve a registered `virtual:foo` import. The synthetic tsconfig is \
         not applied to node_modules files, so the `--alias` fallback must be.",
    );

    assert!(out.bundle_path.exists(), "bundle.mjs should exist");
    let body = fs::read_to_string(&out.bundle_path).expect("read bundle");
    assert!(
        body.contains("NodeModulesVirtualMarker"),
        "the virtual module's source must reach the bundle even though the \
         importer (`_chrome.tsx`) is resident under node_modules; got:\n{body}"
    );

    drop(tmp);
}
