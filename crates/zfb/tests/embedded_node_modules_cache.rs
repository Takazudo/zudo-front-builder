use std::fs::{self, OpenOptions};
use std::path::{Path, PathBuf};
use std::process::{Child, Command};

use anyhow::{Context, Result};
use include_dir::{Dir, DirEntry, File};

use cache::{
    acquire_cached_embedded_node_modules, embedded_node_modules_cache_enabled, test_cache_key,
    EmbeddedNodeModulesLease, EMBEDDED_NODE_MODULES_CACHE_SCHEMA, ZFB_EMBEDDED_NODE_MODULES_CACHE,
};

static FIXTURE_ENTRIES: &[DirEntry<'static>] = &[
    DirEntry::File(File::new(
        "@scope/pkg/index.js",
        b"export const cacheRace = 1;\n",
    )),
    DirEntry::File(File::new(
        "@scope/pkg/package.json",
        br#"{"name":"@scope/pkg","type":"module"}
"#,
    )),
    DirEntry::File(File::new("plain/readme.txt", b"stable embedded bytes\n")),
    DirEntry::File(File::new("bin/esbuild", b"must not enter node_modules\n")),
];
static FIXTURE: Dir<'static> = Dir::new("", FIXTURE_ENTRIES);

const MODE_ENV: &str = "ZFB_CACHE_TEST_MODE";
const ROOT_ENV: &str = "ZFB_CACHE_TEST_ROOT";
const CACHE_PARENT_ENV: &str = "ZFB_CACHE_TEST_PARENT";
const RESULT_ENV: &str = "ZFB_CACHE_TEST_RESULT";

#[test]
fn cache_process_worker() -> Result<()> {
    let Ok(mode) = std::env::var(MODE_ENV) else {
        return Ok(());
    };
    let project_root = PathBuf::from(std::env::var_os(ROOT_ENV).context("missing test root")?);
    let cache_parent =
        PathBuf::from(std::env::var_os(CACHE_PARENT_ENV).context("missing cache parent")?);
    let result_root = PathBuf::from(std::env::var_os(RESULT_ENV).context("missing result root")?);
    fs::create_dir_all(&result_root)?;

    match mode.as_str() {
        "acquire" => worker_acquire(&project_root, &result_root),
        "leave-staging" => worker_leave_staging(&cache_parent),
        "flag" => {
            let verdict = if embedded_node_modules_cache_enabled() {
                "enabled"
            } else {
                "disabled"
            };
            fs::write(
                result_root.join(format!("{}.flag", std::process::id())),
                verdict,
            )?;
            Ok(())
        }
        other => anyhow::bail!("unknown cache test worker mode {other}"),
    }
}

#[test]
fn concurrent_cold_start_publishes_once_and_all_processes_borrow() -> Result<()> {
    let fixture = TestRoots::new()?;
    let mut children: Vec<Child> = (0..8)
        .map(|_| spawn_worker("acquire", &fixture, None))
        .collect::<Result<_>>()?;
    for child in &mut children {
        let status = child.wait()?;
        assert!(status.success(), "cold-start worker failed: {status}");
    }

    let results = result_files(&fixture.results, "borrowed")?;
    assert_eq!(
        results.len(),
        8,
        "every racing process must borrow the cache"
    );
    assert!(result_files(&fixture.results, "fallback")?.is_empty());
    assert_valid_single_publication(&fixture.isolated)?;
    assert_eq!(
        fs::read_dir(schema_root(&fixture.isolated).join("staging"))?.count(),
        0,
        "losing cold-start processes must re-check instead of staging again"
    );
    Ok(())
}

#[test]
fn interrupted_staging_from_exited_process_does_not_poison_publication() -> Result<()> {
    let fixture = TestRoots::new()?;
    let status = spawn_worker("leave-staging", &fixture, None)?.wait()?;
    assert!(status.success(), "staging worker failed: {status}");

    let staging = schema_root(&fixture.isolated).join("staging");
    assert_eq!(
        fs::read_dir(&staging)?.count(),
        1,
        "crashed worker must leave staging evidence"
    );

    let status = spawn_worker("acquire", &fixture, None)?.wait()?;
    assert!(status.success(), "recovery worker failed: {status}");
    assert_eq!(result_files(&fixture.results, "borrowed")?.len(), 1);
    assert!(result_files(&fixture.results, "fallback")?.is_empty());
    assert_valid_single_publication(&fixture.isolated)?;
    Ok(())
}

#[test]
fn corrupt_unreadable_and_wrong_schema_cache_states_always_fall_back() -> Result<()> {
    for state in ["corrupt", "wrong-schema", "unreadable"] {
        let fixture = TestRoots::new()?;
        install_unusable_entry(&fixture.isolated, state)?;
        let status = spawn_worker("acquire", &fixture, None)?.wait()?;
        restore_unusable_entry_permissions(&fixture.isolated, state)?;
        assert!(status.success(), "{state} fallback worker failed: {status}");
        assert_eq!(
            result_files(&fixture.results, "owned")?.len(),
            1,
            "{state} must return the owned extraction"
        );
        assert_eq!(
            result_files(&fixture.results, "fallback")?.len(),
            1,
            "{state} must invoke the fallback exactly once"
        );
        assert!(result_files(&fixture.results, "borrowed")?.is_empty());
    }
    Ok(())
}

#[test]
fn cache_flag_is_default_off_and_accepts_only_one_or_true() -> Result<()> {
    for (value, expected) in [
        (None, "disabled"),
        (Some(""), "disabled"),
        (Some("0"), "disabled"),
        (Some("yes"), "disabled"),
        (Some(" true "), "enabled"),
        (Some("TRUE"), "enabled"),
        (Some("1"), "enabled"),
    ] {
        let fixture = TestRoots::new()?;
        let status = spawn_worker("flag", &fixture, value)?.wait()?;
        assert!(status.success());
        let result = result_files(&fixture.results, "flag")?;
        assert_eq!(result.len(), 1);
        assert_eq!(
            fs::read_to_string(&result[0])?,
            expected,
            "flag value {value:?}"
        );
    }
    Ok(())
}

fn worker_acquire(project_root: &Path, result_root: &Path) -> Result<()> {
    let fallback_result = result_root.to_path_buf();
    let lease = acquire_cached_embedded_node_modules(project_root, &FIXTURE, move || {
        fs::write(
            fallback_result.join(format!("{}.fallback", std::process::id())),
            b"fallback\n",
        )?;
        owned_fixture()
    })?;

    match lease {
        EmbeddedNodeModulesLease::Borrowed {
            guard,
            node_modules,
        } => {
            assert_fixture(&node_modules)?;
            fs::write(
                result_root.join(format!("{}.borrowed", std::process::id())),
                b"borrowed\n",
            )?;
            drop(guard);
        }
        EmbeddedNodeModulesLease::Owned {
            tempdir,
            node_modules,
        } => {
            assert_fixture(&node_modules)?;
            fs::write(
                result_root.join(format!("{}.owned", std::process::id())),
                b"owned\n",
            )?;
            drop(tempdir);
        }
    }
    Ok(())
}

fn worker_leave_staging(isolated_root: &Path) -> Result<()> {
    let key = test_cache_key(&FIXTURE)?;
    let staging = schema_root(isolated_root)
        .join("staging")
        .join(format!(".{key}.{}.deadbeef", std::process::id()));
    fs::create_dir_all(staging.join("tree/node_modules"))?;
    let owner = OpenOptions::new()
        .read(true)
        .write(true)
        .create(true)
        .truncate(false)
        .open(staging.join(".owner.lock"))?;
    owner.lock()?;
    fs::write(staging.join("tree/node_modules/partial"), b"partial")?;
    std::process::exit(0);
}

fn owned_fixture() -> Result<(tempfile::TempDir, PathBuf)> {
    let tempdir = tempfile::tempdir()?;
    let node_modules = tempdir.path().join("node_modules");
    fs::create_dir_all(&node_modules)?;
    for entry in FIXTURE.entries() {
        let DirEntry::File(file) = entry else {
            continue;
        };
        let path = file.path();
        if path
            .components()
            .next()
            .and_then(|part| part.as_os_str().to_str())
            == Some("bin")
        {
            continue;
        }
        let target = node_modules.join(path);
        fs::create_dir_all(target.parent().context("fixture file parent")?)?;
        fs::write(target, file.contents())?;
    }
    Ok((tempdir, node_modules))
}

fn assert_fixture(node_modules: &Path) -> Result<()> {
    assert_eq!(
        fs::read_to_string(node_modules.join("@scope/pkg/index.js"))?,
        "export const cacheRace = 1;\n"
    );
    assert!(!node_modules.join("bin/esbuild").exists());
    Ok(())
}

fn install_unusable_entry(isolated_root: &Path, state: &str) -> Result<()> {
    let key = test_cache_key(&FIXTURE)?;
    let schema = schema_root(isolated_root);
    fs::create_dir_all(schema.join("done"))?;
    fs::create_dir_all(
        schema
            .join("trees")
            .join(&key)
            .join("node_modules/@scope/pkg"),
    )?;
    fs::create_dir_all(schema.join("locks"))?;
    fs::create_dir_all(schema.join("staging"))?;

    #[cfg(unix)]
    fs::write(schema.join("locks").join(format!("{key}.lock")), b"")?;
    #[cfg(not(unix))]
    fs::create_dir_all(schema.join("locks").join(format!("{key}.lock")))?;

    let marker = schema.join("done").join(format!("{key}.done"));
    match state {
        "corrupt" => fs::write(marker, b"not a marker\n")?,
        "wrong-schema" => fs::write(marker, format!("schema=999\nkey={key}\n"))?,
        "unreadable" => {
            fs::write(
                marker,
                format!("schema={}\nkey={key}\n", EMBEDDED_NODE_MODULES_CACHE_SCHEMA),
            )?;
            let unreadable = schema
                .join("trees")
                .join(&key)
                .join("node_modules/@scope/pkg/index.js");
            fs::write(&unreadable, b"export const cacheRace = 1;\n")?;
            #[cfg(unix)]
            {
                use std::os::unix::fs::PermissionsExt;
                fs::set_permissions(&unreadable, fs::Permissions::from_mode(0o000))?;
            }
        }
        _ => unreachable!(),
    }

    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        // Ensure repair fails only after the malformed or unreadable entry
        // has been validated and rejected.
        fs::set_permissions(schema.join("staging"), fs::Permissions::from_mode(0o555))?;
    }
    Ok(())
}

fn restore_unusable_entry_permissions(isolated_root: &Path, state: &str) -> Result<()> {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let key = test_cache_key(&FIXTURE)?;
        let schema = schema_root(isolated_root);
        fs::set_permissions(schema.join("staging"), fs::Permissions::from_mode(0o755))?;
        if state == "unreadable" {
            fs::set_permissions(
                schema
                    .join("trees")
                    .join(key)
                    .join("node_modules/@scope/pkg/index.js"),
                fs::Permissions::from_mode(0o644),
            )?;
        }
    }
    #[cfg(not(unix))]
    let _ = (isolated_root, state);
    Ok(())
}

fn assert_valid_single_publication(isolated_root: &Path) -> Result<()> {
    let key = test_cache_key(&FIXTURE)?;
    let schema = schema_root(isolated_root);
    let markers: Vec<_> = fs::read_dir(schema.join("done"))?.collect::<std::io::Result<_>>()?;
    let trees: Vec<_> = fs::read_dir(schema.join("trees"))?.collect::<std::io::Result<_>>()?;
    assert_eq!(markers.len(), 1);
    assert_eq!(trees.len(), 1);
    assert_eq!(
        markers[0].file_name().to_string_lossy(),
        format!("{key}.done")
    );
    assert_eq!(trees[0].file_name().to_string_lossy(), key);
    assert_eq!(
        fs::read_to_string(markers[0].path())?,
        format!(
            "schema={}\nkey={}\n",
            EMBEDDED_NODE_MODULES_CACHE_SCHEMA,
            test_cache_key(&FIXTURE)?
        )
    );
    assert_fixture(&trees[0].path().join("node_modules"))
}

fn spawn_worker(mode: &str, roots: &TestRoots, flag: Option<&str>) -> Result<Child> {
    let executable = std::env::current_exe()?;
    let mut command = Command::new(executable);
    command
        .arg("--exact")
        .arg("cache_process_worker")
        .arg("--nocapture")
        .arg("--test-threads=1")
        .env(MODE_ENV, mode)
        .env(ROOT_ENV, &roots.project)
        .env(CACHE_PARENT_ENV, &roots.isolated)
        .env(RESULT_ENV, &roots.results)
        .env("TMPDIR", &roots.isolated)
        .env("TMP", &roots.isolated)
        .env("TEMP", &roots.isolated)
        .env_remove(ZFB_EMBEDDED_NODE_MODULES_CACHE);
    if let Some(value) = flag {
        command.env(ZFB_EMBEDDED_NODE_MODULES_CACHE, value);
    }
    command.spawn().context("spawn cache test worker")
}

fn schema_root(isolated_root: &Path) -> PathBuf {
    isolated_root
        .join("zfb-embedded-node-modules-cache")
        .join(format!("schema-{EMBEDDED_NODE_MODULES_CACHE_SCHEMA}"))
}

fn result_files(root: &Path, extension: &str) -> Result<Vec<PathBuf>> {
    let mut results = Vec::new();
    for entry in fs::read_dir(root)? {
        let entry = entry?;
        if entry.path().extension().and_then(|value| value.to_str()) == Some(extension) {
            results.push(entry.path());
        }
    }
    Ok(results)
}

struct TestRoots {
    _owner: tempfile::TempDir,
    isolated: PathBuf,
    project: PathBuf,
    results: PathBuf,
}

impl TestRoots {
    fn new() -> Result<Self> {
        let owner = tempfile::tempdir()?;
        let isolated = owner.path().join("isolated-cache-parent");
        let project = owner.path().join("project");
        let results = owner.path().join("results");
        fs::create_dir_all(&isolated)?;
        fs::create_dir_all(&project)?;
        fs::create_dir_all(&results)?;
        Ok(Self {
            _owner: owner,
            isolated,
            project,
            results,
        })
    }
}
