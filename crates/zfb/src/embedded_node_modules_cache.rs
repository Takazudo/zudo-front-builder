use std::fs::{self, File, OpenOptions};
use std::io::{Read, Write};
use std::path::{Component, Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};
use std::time::{Duration, SystemTime, UNIX_EPOCH};

use anyhow::{anyhow, Context, Result};
use include_dir::{Dir, DirEntry};
use sha2::{Digest, Sha256};

pub(crate) const EMBEDDED_NODE_MODULES_CACHE_SCHEMA: u32 = 1;
pub(crate) const ZFB_EMBEDDED_NODE_MODULES_CACHE: &str = "ZFB_EMBEDDED_NODE_MODULES_CACHE";

const CACHE_DIR: &str = "zfb-embedded-node-modules-cache";
const LOCKS_DIR: &str = "locks";
const DONE_DIR: &str = "done";
const TREES_DIR: &str = "trees";
const STAGING_DIR: &str = "staging";
const STAGING_MIN_AGE: Duration = Duration::from_secs(5 * 60);
const PUBLISHED_MAX_AGE: Duration = Duration::from_secs(30 * 24 * 60 * 60);
const REAP_LIMIT: usize = 64;
const IO_CHUNK: usize = 64 * 1024;

static NONCE: AtomicU64 = AtomicU64::new(0);

pub(crate) enum EmbeddedNodeModulesLease {
    Owned {
        tempdir: tempfile::TempDir,
        node_modules: PathBuf,
    },
    Borrowed {
        guard: CacheReadGuard,
        node_modules: PathBuf,
    },
}

impl EmbeddedNodeModulesLease {
    pub(crate) fn node_modules(&self) -> &Path {
        match self {
            Self::Owned {
                tempdir,
                node_modules,
            } => {
                let _keep_alive = tempdir;
                node_modules
            }
            Self::Borrowed {
                guard,
                node_modules,
            } => {
                let _keep_alive = guard;
                node_modules
            }
        }
    }
}

pub(crate) struct CacheReadGuard {
    lock: Option<File>,
}

impl Drop for CacheReadGuard {
    fn drop(&mut self) {
        if let Some(lock) = self.lock.take() {
            let _ = lock.unlock();
        }
    }
}

pub(crate) fn embedded_node_modules_cache_enabled() -> bool {
    std::env::var(ZFB_EMBEDDED_NODE_MODULES_CACHE)
        .ok()
        .map(|value| {
            let value = value.trim();
            value == "1" || value.eq_ignore_ascii_case("true")
        })
        .unwrap_or(false)
}

pub(crate) fn acquire_cached_embedded_node_modules<F>(
    project_root: &Path,
    embedded_vendor: &Dir<'_>,
    owned_fallback: F,
) -> Result<EmbeddedNodeModulesLease>
where
    F: FnOnce() -> Result<(tempfile::TempDir, PathBuf)>,
{
    match acquire_from_cache(project_root, embedded_vendor) {
        Ok(lease) => Ok(lease),
        Err(error) => {
            tracing::debug!(error = %error, "embedded node_modules cache unavailable; using owned extraction");
            let (tempdir, node_modules) = owned_fallback()?;
            Ok(EmbeddedNodeModulesLease::Owned {
                tempdir,
                node_modules,
            })
        }
    }
}

pub(crate) fn acquire_embedded_node_modules_if_enabled<F>(
    project_root: &Path,
    embedded_vendor: &Dir<'_>,
    owned_fallback: F,
) -> Result<EmbeddedNodeModulesLease>
where
    F: FnOnce() -> Result<(tempfile::TempDir, PathBuf)>,
{
    if embedded_node_modules_cache_enabled() {
        acquire_cached_embedded_node_modules(project_root, embedded_vendor, owned_fallback)
    } else {
        let (tempdir, node_modules) = owned_fallback()?;
        Ok(EmbeddedNodeModulesLease::Owned {
            tempdir,
            node_modules,
        })
    }
}

fn acquire_from_cache(
    project_root: &Path,
    embedded_vendor: &Dir<'_>,
) -> Result<EmbeddedNodeModulesLease> {
    let key = embedded_node_modules_cache_key(embedded_vendor)?;
    let parent = zfb_build::bundler::shadow_parent_dir(project_root)
        .context("resolve embedded node_modules cache parent")?;
    let cache_root = parent.join(CACHE_DIR);
    let schema_root = cache_root.join(schema_dir_name(EMBEDDED_NODE_MODULES_CACHE_SCHEMA));
    create_schema_layout(&cache_root, &schema_root)?;
    reap_embedded_node_modules_cache(&cache_root);

    let lock_path = schema_root.join(LOCKS_DIR).join(format!("{key}.lock"));
    let marker_path = schema_root.join(DONE_DIR).join(format!("{key}.done"));
    let tree_path = schema_root.join(TREES_DIR).join(&key);
    let lock = open_lock(&lock_path)?;

    if marker_path.exists() {
        lock.lock_shared()
            .context("lock cache key for shared read")?;
        if validate_published_tree(
            &tree_path,
            &marker_path,
            &key,
            EMBEDDED_NODE_MODULES_CACHE_SCHEMA,
        )
        .is_ok()
        {
            touch_valid_marker(&marker_path, &key, EMBEDDED_NODE_MODULES_CACHE_SCHEMA);
            return Ok(borrowed(lock, tree_path));
        }
        lock.unlock().context("unlock invalid shared cache entry")?;
    }

    lock.lock().context("lock cache key for publication")?;
    if validate_published_tree(
        &tree_path,
        &marker_path,
        &key,
        EMBEDDED_NODE_MODULES_CACHE_SCHEMA,
    )
    .is_ok()
    {
        lock.unlock()
            .context("release publisher lock after recheck")?;
        return acquire_valid_shared(lock, &tree_path, &marker_path, &key);
    }

    if let Err(error) = publish_under_exclusive_lock(
        &schema_root,
        &tree_path,
        &marker_path,
        &key,
        embedded_vendor,
    ) {
        let _ = lock.unlock();
        return Err(error);
    }
    lock.unlock().context("release publisher lock")?;
    acquire_valid_shared(lock, &tree_path, &marker_path, &key)
}

fn acquire_valid_shared(
    lock: File,
    tree_path: &Path,
    marker_path: &Path,
    key: &str,
) -> Result<EmbeddedNodeModulesLease> {
    lock.lock_shared()
        .context("reacquire shared cache key lock")?;
    if let Err(error) = validate_published_tree(
        tree_path,
        marker_path,
        key,
        EMBEDDED_NODE_MODULES_CACHE_SCHEMA,
    ) {
        let _ = lock.unlock();
        return Err(error.context("cache changed before shared lease acquisition"));
    }
    touch_valid_marker(marker_path, key, EMBEDDED_NODE_MODULES_CACHE_SCHEMA);
    Ok(borrowed(lock, tree_path.to_path_buf()))
}

fn borrowed(lock: File, tree_path: PathBuf) -> EmbeddedNodeModulesLease {
    EmbeddedNodeModulesLease::Borrowed {
        guard: CacheReadGuard { lock: Some(lock) },
        node_modules: tree_path.join("node_modules"),
    }
}

fn embedded_node_modules_cache_key(embedded_vendor: &Dir<'_>) -> Result<String> {
    let files = embedded_files(embedded_vendor)?;
    let mut hasher = Sha256::new();
    hasher.update(EMBEDDED_NODE_MODULES_CACHE_SCHEMA.to_le_bytes());
    for file in files {
        hash_header(
            &mut hasher,
            file.path.as_bytes(),
            file.contents.len() as u64,
        );
        for chunk in file.contents.chunks(IO_CHUNK) {
            hasher.update(chunk);
        }
    }
    Ok(short_hex(hasher.finalize().as_slice()))
}

fn validate_published_tree(
    tree_path: &Path,
    marker_path: &Path,
    expected_key: &str,
    schema: u32,
) -> Result<()> {
    let marker_meta = fs::symlink_metadata(marker_path).context("read cache marker metadata")?;
    if !marker_meta.file_type().is_file() || marker_meta.file_type().is_symlink() {
        return Err(anyhow!("cache marker is not a regular file"));
    }
    let expected_marker = marker_contents(schema, expected_key);
    if fs::read(marker_path).context("read cache marker")? != expected_marker.as_bytes() {
        return Err(anyhow!("cache marker schema or key mismatch"));
    }

    let tree_meta = fs::symlink_metadata(tree_path).context("read published tree metadata")?;
    if !tree_meta.file_type().is_dir() || tree_meta.file_type().is_symlink() {
        return Err(anyhow!("published tree is not a real directory"));
    }
    let node_modules = tree_path.join("node_modules");
    let actual_key = filesystem_tree_key(&node_modules, schema)?;
    if actual_key != expected_key {
        return Err(anyhow!("published tree digest mismatch"));
    }
    Ok(())
}

fn publish_under_exclusive_lock(
    schema_root: &Path,
    tree_path: &Path,
    marker_path: &Path,
    key: &str,
    embedded_vendor: &Dir<'_>,
) -> Result<()> {
    let staging_root = schema_root.join(STAGING_DIR);
    let staging = staging_root.join(staging_name(key));
    fs::create_dir(&staging)
        .with_context(|| format!("create staging dir {}", staging.display()))?;
    let owner_path = staging.join(".owner.lock");
    let owner = open_lock(&owner_path).context("create staging owner lock")?;
    owner.lock().context("lock staging ownership")?;

    let result = (|| {
        let staged_tree = staging.join("tree");
        let staged_node_modules = staged_tree.join("node_modules");
        fs::create_dir_all(&staged_node_modules).context("create staged node_modules")?;
        extract_embedded_vendor(embedded_vendor, &staged_node_modules)?;
        let staged_key =
            filesystem_tree_key(&staged_node_modules, EMBEDDED_NODE_MODULES_CACHE_SCHEMA)?;
        if staged_key != key {
            return Err(anyhow!("staged embedded tree failed digest validation"));
        }

        let mut displaced = None;
        if tree_path.exists() {
            let displaced_root = staging_root.join(staging_name(key));
            fs::create_dir(&displaced_root).context("create invalid-tree reap staging dir")?;
            let displaced_owner_path = displaced_root.join(".owner.lock");
            let displaced_owner = open_lock(&displaced_owner_path)?;
            displaced_owner.lock()?;
            let displaced_tree = displaced_root.join("tree");
            if let Err(error) = fs::rename(tree_path, &displaced_tree) {
                let _ = displaced_owner.unlock();
                drop(displaced_owner);
                let _ = fs::remove_dir_all(&displaced_root);
                return Err(error).context("move invalid published tree aside");
            }
            displaced = Some((displaced_root, displaced_owner));
        }

        fs::rename(&staged_tree, tree_path).context("atomically publish embedded tree")?;
        if let Err(error) = validate_tree_only(tree_path, key, EMBEDDED_NODE_MODULES_CACHE_SCHEMA) {
            return Err(error.context("validate published embedded tree"));
        }

        if marker_path.exists() {
            fs::remove_file(marker_path).context("remove invalid cache marker")?;
        }
        publish_marker(marker_path, key, EMBEDDED_NODE_MODULES_CACHE_SCHEMA)?;
        validate_published_tree(
            tree_path,
            marker_path,
            key,
            EMBEDDED_NODE_MODULES_CACHE_SCHEMA,
        )?;

        if let Some((displaced_root, displaced_owner)) = displaced {
            let _ = displaced_owner.unlock();
            drop(displaced_owner);
            let _ = fs::remove_dir_all(displaced_root);
        }
        Ok(())
    })();

    let _ = owner.unlock();
    drop(owner);
    let _ = fs::remove_dir_all(&staging);
    result
}

fn reap_embedded_node_modules_cache(cache_root: &Path) {
    let _ = reap_staging(cache_root);
    let _ = reap_published(cache_root);
}

fn reap_staging(cache_root: &Path) -> Result<()> {
    let mut inspected = 0usize;
    for schema_entry in read_dir_fail_closed(cache_root)? {
        if inspected >= REAP_LIMIT {
            break;
        }
        let schema_path = schema_entry.path();
        if parse_schema_dir(&schema_entry.file_name()).is_none() || !real_dir(&schema_path) {
            continue;
        }
        let staging_path = schema_path.join(STAGING_DIR);
        if !real_dir(&staging_path) {
            continue;
        }
        for entry in read_dir_fail_closed(&staging_path)? {
            if inspected >= REAP_LIMIT {
                break;
            }
            inspected += 1;
            let name = entry.file_name();
            let Some(name) = name.to_str() else { continue };
            if !valid_staging_name(name)
                || !real_dir(&entry.path())
                || !older_than(&entry.path(), STAGING_MIN_AGE)
            {
                continue;
            }
            let owner_path = entry.path().join(".owner.lock");
            match OpenOptions::new().read(true).write(true).open(&owner_path) {
                Ok(owner) => {
                    if owner.try_lock().is_err() {
                        continue;
                    }
                    let _ = owner.unlock();
                    drop(owner);
                    let _ = fs::remove_dir_all(entry.path());
                }
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                    let _ = fs::remove_dir_all(entry.path());
                }
                Err(_) => {}
            }
        }
    }
    Ok(())
}

fn reap_published(cache_root: &Path) -> Result<()> {
    let mut inspected = 0usize;
    for schema_entry in read_dir_fail_closed(cache_root)? {
        let Some(schema) = parse_schema_dir(&schema_entry.file_name()) else {
            continue;
        };
        let schema_path = schema_entry.path();
        if !real_dir(&schema_path) {
            continue;
        }
        let locks_path = schema_path.join(LOCKS_DIR);
        let done_path = schema_path.join(DONE_DIR);
        let trees_path = schema_path.join(TREES_DIR);
        if !real_dir(&locks_path) || !real_dir(&done_path) || !real_dir(&trees_path) {
            continue;
        }
        for marker_entry in read_dir_fail_closed(&done_path)? {
            if inspected >= REAP_LIMIT {
                return Ok(());
            }
            inspected += 1;
            let Some(key) = marker_key(&marker_entry.file_name()) else {
                continue;
            };
            let marker_path = marker_entry.path();
            if !older_than(&marker_path, PUBLISHED_MAX_AGE) {
                continue;
            }
            let lock_path = locks_path.join(format!("{key}.lock"));
            let Ok(lock) = open_lock(&lock_path) else {
                continue;
            };
            if lock.try_lock().is_err() {
                continue;
            }
            let tree_path = trees_path.join(&key);
            let still_old = older_than(&marker_path, PUBLISHED_MAX_AGE);
            let layout_valid =
                validate_published_tree(&tree_path, &marker_path, &key, schema).is_ok();
            if still_old && layout_valid && fs::remove_file(&marker_path).is_ok() {
                let _ = fs::remove_dir_all(&tree_path);
            }
            let _ = lock.unlock();
        }
    }
    Ok(())
}

fn create_schema_layout(cache_root: &Path, schema_root: &Path) -> Result<()> {
    ensure_real_directory(cache_root)?;
    ensure_real_directory(schema_root)?;
    for name in [LOCKS_DIR, DONE_DIR, TREES_DIR, STAGING_DIR] {
        let path = schema_root.join(name);
        ensure_real_directory(&path)?;
    }
    Ok(())
}

fn ensure_real_directory(path: &Path) -> Result<()> {
    match fs::symlink_metadata(path) {
        Ok(metadata) => {
            if !metadata.file_type().is_dir() || metadata.file_type().is_symlink() {
                return Err(anyhow!(
                    "cache layout path is not a real directory: {}",
                    path.display()
                ));
            }
            return Ok(());
        }
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
        Err(error) => return Err(error).context("inspect cache layout directory"),
    }

    match fs::create_dir(path) {
        Ok(()) => {}
        Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => {}
        Err(error) => {
            return Err(error).with_context(|| format!("create cache layout {}", path.display()))
        }
    }
    let metadata = fs::symlink_metadata(path).context("verify created cache layout directory")?;
    if !metadata.file_type().is_dir() || metadata.file_type().is_symlink() {
        return Err(anyhow!(
            "cache layout path is not a real directory: {}",
            path.display()
        ));
    }
    Ok(())
}

fn extract_embedded_vendor(embedded: &Dir<'_>, dest: &Path) -> Result<()> {
    for file in embedded_files(embedded)? {
        let target = dest.join(Path::new(&file.path));
        if let Some(parent) = target.parent() {
            fs::create_dir_all(parent)?;
        }
        let mut output = OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&target)?;
        for chunk in file.contents.chunks(IO_CHUNK) {
            output.write_all(chunk)?;
        }
        output.sync_all()?;
    }
    Ok(())
}

struct EmbeddedFile<'a> {
    path: String,
    contents: &'a [u8],
}

fn embedded_files<'a>(embedded: &'a Dir<'a>) -> Result<Vec<EmbeddedFile<'a>>> {
    fn visit<'a>(dir: &'a Dir<'a>, files: &mut Vec<EmbeddedFile<'a>>) -> Result<()> {
        for entry in dir.entries() {
            match entry {
                DirEntry::Dir(child) => visit(child, files)?,
                DirEntry::File(file) => {
                    let path = normalized_relative_path(file.path())?;
                    if path.split('/').next() == Some("bin") {
                        continue;
                    }
                    files.push(EmbeddedFile {
                        path,
                        contents: file.contents(),
                    });
                }
            }
        }
        Ok(())
    }

    let mut files = Vec::new();
    visit(embedded, &mut files)?;
    files.sort_by(|a, b| a.path.as_bytes().cmp(b.path.as_bytes()));
    Ok(files)
}

fn filesystem_tree_key(root: &Path, schema: u32) -> Result<String> {
    let metadata = fs::symlink_metadata(root).context("read node_modules metadata")?;
    if !metadata.file_type().is_dir() || metadata.file_type().is_symlink() {
        return Err(anyhow!("node_modules is not a real directory"));
    }
    let mut paths = Vec::new();
    collect_regular_files(root, root, &mut paths)?;
    paths.sort_by(|a, b| a.0.as_bytes().cmp(b.0.as_bytes()));

    let mut hasher = Sha256::new();
    hasher.update(schema.to_le_bytes());
    let mut buffer = [0u8; IO_CHUNK];
    for (relative, path) in paths {
        let metadata = fs::symlink_metadata(&path)?;
        if !metadata.file_type().is_file() || metadata.file_type().is_symlink() {
            return Err(anyhow!("cache tree contains a non-regular entry"));
        }
        hash_header(&mut hasher, relative.as_bytes(), metadata.len());
        let mut input = File::open(&path)?;
        let mut observed = 0u64;
        loop {
            let count = input.read(&mut buffer)?;
            if count == 0 {
                break;
            }
            observed += count as u64;
            hasher.update(&buffer[..count]);
        }
        if observed != metadata.len() {
            return Err(anyhow!("cache file length changed while validating"));
        }
    }
    Ok(short_hex(hasher.finalize().as_slice()))
}

fn collect_regular_files(
    root: &Path,
    dir: &Path,
    files: &mut Vec<(String, PathBuf)>,
) -> Result<()> {
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        let path = entry.path();
        let metadata = fs::symlink_metadata(&path)?;
        if metadata.file_type().is_symlink() {
            return Err(anyhow!("cache tree contains a symlink"));
        }
        if metadata.file_type().is_dir() {
            collect_regular_files(root, &path, files)?;
        } else if metadata.file_type().is_file() {
            let relative = path.strip_prefix(root).context("strip cache tree root")?;
            files.push((normalized_relative_path(relative)?, path));
        } else {
            return Err(anyhow!("cache tree contains a non-regular entry"));
        }
    }
    Ok(())
}

fn validate_tree_only(tree_path: &Path, expected_key: &str, schema: u32) -> Result<()> {
    let actual = filesystem_tree_key(&tree_path.join("node_modules"), schema)?;
    if actual != expected_key {
        return Err(anyhow!("published tree key mismatch"));
    }
    Ok(())
}

fn publish_marker(marker_path: &Path, key: &str, schema: u32) -> Result<()> {
    let file_name = marker_path
        .file_name()
        .and_then(|name| name.to_str())
        .ok_or_else(|| anyhow!("invalid marker path"))?;
    let temporary = marker_path.with_file_name(format!(".{file_name}.{}.tmp", unique_nonce()));
    let result = (|| {
        let mut output = OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&temporary)?;
        output.write_all(marker_contents(schema, key).as_bytes())?;
        output.sync_all()?;
        drop(output);
        fs::rename(&temporary, marker_path).context("atomically publish cache marker")?;
        Ok(())
    })();
    if result.is_err() {
        let _ = fs::remove_file(&temporary);
    }
    result
}

fn touch_valid_marker(marker_path: &Path, key: &str, schema: u32) {
    if let Ok(mut marker) = OpenOptions::new().write(true).open(marker_path) {
        let _ = marker.write_all(marker_contents(schema, key).as_bytes());
    }
}

fn open_lock(path: &Path) -> Result<File> {
    OpenOptions::new()
        .read(true)
        .write(true)
        .create(true)
        .truncate(false)
        .open(path)
        .with_context(|| format!("open cache lock {}", path.display()))
}

fn normalized_relative_path(path: &Path) -> Result<String> {
    let mut output = String::new();
    for component in path.components() {
        let Component::Normal(value) = component else {
            return Err(anyhow!("embedded/cache path is not strictly relative"));
        };
        let value = value
            .to_str()
            .ok_or_else(|| anyhow!("cache path is not UTF-8"))?;
        if !output.is_empty() {
            output.push('/');
        }
        output.push_str(value);
    }
    if output.is_empty() {
        return Err(anyhow!("empty cache file path"));
    }
    Ok(output)
}

fn hash_header(hasher: &mut Sha256, path: &[u8], length: u64) {
    hasher.update((path.len() as u64).to_le_bytes());
    hasher.update(path);
    hasher.update(length.to_le_bytes());
}

fn short_hex(bytes: &[u8]) -> String {
    let mut output = String::with_capacity(16);
    for byte in &bytes[..8] {
        use std::fmt::Write as _;
        let _ = write!(output, "{byte:02x}");
    }
    output
}

fn marker_contents(schema: u32, key: &str) -> String {
    format!("schema={schema}\nkey={key}\n")
}

fn schema_dir_name(schema: u32) -> String {
    format!("schema-{schema}")
}

fn staging_name(key: &str) -> String {
    format!(".{key}.{}.{}", std::process::id(), unique_nonce())
}

fn unique_nonce() -> String {
    let time = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_nanos();
    let sequence = NONCE.fetch_add(1, Ordering::Relaxed);
    format!("{time:x}{sequence:x}")
}

fn valid_staging_name(name: &str) -> bool {
    let Some(rest) = name.strip_prefix('.') else {
        return false;
    };
    let mut parts = rest.split('.');
    matches!(
        (parts.next(), parts.next(), parts.next(), parts.next()),
        (Some(key), Some(pid), Some(nonce), None)
            if valid_key(key)
                && !pid.is_empty() && pid.bytes().all(|byte| byte.is_ascii_digit())
                && !nonce.is_empty() && nonce.bytes().all(|byte| byte.is_ascii_hexdigit())
    )
}

fn valid_key(key: &str) -> bool {
    key.len() == 16
        && key
            .bytes()
            .all(|byte| byte.is_ascii_hexdigit() && !byte.is_ascii_uppercase())
}

fn marker_key(name: &std::ffi::OsStr) -> Option<String> {
    let name = name.to_str()?;
    let key = name.strip_suffix(".done")?;
    valid_key(key).then(|| key.to_string())
}

fn parse_schema_dir(name: &std::ffi::OsStr) -> Option<u32> {
    name.to_str()?.strip_prefix("schema-")?.parse().ok()
}

fn real_dir(path: &Path) -> bool {
    fs::symlink_metadata(path)
        .map(|metadata| metadata.file_type().is_dir() && !metadata.file_type().is_symlink())
        .unwrap_or(false)
}

fn older_than(path: &Path, age: Duration) -> bool {
    fs::symlink_metadata(path)
        .and_then(|metadata| metadata.modified())
        .ok()
        .and_then(|modified| SystemTime::now().duration_since(modified).ok())
        .map(|elapsed| elapsed >= age)
        .unwrap_or(false)
}

fn read_dir_fail_closed(path: &Path) -> Result<Vec<fs::DirEntry>> {
    let entries = match fs::read_dir(path) {
        Ok(entries) => entries,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(Vec::new()),
        Err(error) => return Err(error.into()),
    };
    entries
        .collect::<std::io::Result<Vec<_>>>()
        .map_err(Into::into)
}

