//! Regression tests for #3002 (Plugin Alias In Node Modules epic #3014,
//! sub-issue #3017): a route/island entrypoint whose realpath is **under
//! `node_modules`** must be able to `import` a plugin-registered
//! `ctx.addAlias` specifier whose target is a single existing file, not
//! just a plugin-registered `virtual:*` module.
//!
//! ## Why the existing exact-match coverage missed this
//!
//! `exact_match_resolution.rs` registers an alias and imports it from an
//! island under `<root>/components/` — i.e. NOT under `node_modules`. That
//! import resolves through the synthetic tsconfig's `compilerOptions.paths`.
//! But esbuild does **not** apply `compilerOptions.paths` to a source file
//! resident under `node_modules`: its resolver's `tsConfigForDir` returns
//! `nil` the moment `isInsideNodeModules` is true, *before* consulting the
//! `--tsconfig` / `--tsconfig-raw` override — the same gap #1263 already
//! fixed for virtual modules by ALSO emitting an esbuild
//! `--alias:<spec>=<tmp.mjs>` flag (see `node_modules_virtual_module.rs`).
//!
//! #3002 extends the same `--alias` fallback to plugin aliases (`@/foo`)
//! whose resolved target is a single *existing file* — a directory target
//! stays tsconfig-paths-only, because esbuild's `--alias` is
//! prefix-with-slash and would silently rewrite `@/foo/bar` into a real
//! file under a directory alias, contradicting the #269 exact-match
//! contract. See
//! `zfb_plugin_resolver::ResolverInputs::plugin_alias_args`'s doc comment
//! for the full three-gate policy (is_file, user-wins, no slash-prefix
//! collision) — this file proves the wiring end to end with a real
//! esbuild subprocess, not the gating logic itself (covered in
//! `zfb-plugin-resolver`'s own unit tests).
//!
//! Esbuild gating mirrors the sibling tests: skip with a printed note when
//! no binary is available.

use std::fs;
use std::path::PathBuf;

use zfb_islands::{
    BundleConfig, ClientBundler, EsbuildSubprocessBundler, EsbuildSubprocessConfig, Island,
};
use zfb_test_utils::locate_esbuild;

/// Lay down an island TSX file whose realpath is under
/// `<root>/node_modules/...` — the exact #1263 / #3002 shape (a published
/// preset's route entrypoint). Returns the absolute path to that file.
///
/// A REAL directory, never a symlink: esbuild canonicalises a path before
/// its upward `node_modules` walk, so a symlinked fixture would silently
/// stop reproducing the `isInsideNodeModules` gate this file exists to
/// cover.
fn write_node_modules_island(root: &std::path::Path, island_source: &str) -> PathBuf {
    let nm_routes = root.join("node_modules/@scope/preset/dist/routes");
    fs::create_dir_all(&nm_routes).unwrap();
    let island_path = nm_routes.join("_chrome.tsx");
    fs::write(&island_path, island_source).unwrap();
    island_path
}

/// A single-file alias target at `<root>/src/stub.tsx`, exporting a
/// component named `marker`. Single-file targets are the ones that
/// qualify for the `--alias` fallback (#3002's `is_file()` gate).
fn write_single_file_alias_target(root: &std::path::Path, marker: &str) -> PathBuf {
    fs::create_dir_all(root.join("src")).unwrap();
    let target = root.join("src/stub.tsx");
    fs::write(
        &target,
        format!("export default function {marker}() {{ return null; }}\n"),
    )
    .unwrap();
    target
}

/// A directory-shaped alias target at `<root>/src/dirstub/`, containing an
/// `index.tsx`. Directory targets never qualify for the `--alias`
/// fallback — they stay tsconfig-paths-only (#269's exact-match contract).
fn write_directory_alias_target(root: &std::path::Path) -> PathBuf {
    let dir = root.join("src/dirstub");
    fs::create_dir_all(&dir).unwrap();
    fs::write(
        dir.join("index.tsx"),
        "export default function DirStubMarker() { return null; }\n",
    )
    .unwrap();
    dir
}

fn preact_externals() -> Vec<std::ffi::OsString> {
    vec![
        std::ffi::OsString::from("--external:preact"),
        std::ffi::OsString::from("--external:preact/*"),
        std::ffi::OsString::from("--external:@takazudo/*"),
    ]
}

/// **Primary #3002 gate — happy path.**
///
/// An island whose realpath is under `node_modules` imports the registered
/// single-file alias `@/stub`. Bundling must succeed and the aliased
/// target's marker must reach the bundle. Before #3002 this failed with
/// `Could not resolve "@/stub"`, because the alias only ever reached the
/// synthetic tsconfig, which esbuild ignores for a `node_modules`-resident
/// importer.
#[test]
fn plugin_alias_resolves_from_node_modules_entrypoint() {
    let Some(esbuild) = locate_esbuild() else {
        eprintln!("[node_modules_plugin_alias] no esbuild binary available; skipping.");
        return;
    };

    let tmp = tempfile::tempdir().expect("tempdir");
    let root = tmp.path().to_path_buf();
    let island_path = write_node_modules_island(
        &root,
        "import Marker from \"@/stub\";\n\
         export const Chrome = () => <Marker />;\n",
    );
    let target = write_single_file_alias_target(&root, "NodeModulesAliasMarker");

    let cfg = EsbuildSubprocessConfig {
        extra_args: preact_externals(),
        ..EsbuildSubprocessConfig::default()
    }
    .with_binary_path(esbuild)
    .with_working_dir(&root)
    .with_alias_entries(vec![(
        "@/stub".to_string(),
        target.to_string_lossy().into_owned(),
    )]);
    let bundler = EsbuildSubprocessBundler::new(cfg);
    let bundle_cfg = BundleConfig::default().with_outdir(root.join("dist"));

    let out = bundler
        .bundle(&[Island::new("Chrome", &island_path)], &bundle_cfg)
        .expect(
            "#3002: a route entrypoint whose realpath is under node_modules must \
             resolve a registered single-file plugin alias `@/stub` (the synthetic \
             tsconfig is not applied to node_modules files; the `--alias` fallback \
             must be).",
        );
    let body = String::from_utf8(out.bytes).expect("bundled bytes are valid UTF-8");
    assert!(
        body.contains("NodeModulesAliasMarker"),
        "the aliased target's marker must be bundled into a node_modules \
         entrypoint's output; got:\n{body}"
    );
}

/// **Negative twin — the crux, not an extra (#269 exact-match contract).**
///
/// The same node_modules entrypoint imports `@/stub/deeper` (one slash too
/// many). The `--alias` fallback must NOT silently resolve it: the target
/// is a single file, so `@/stub/deeper` remaps to `<stub.tsx>/deeper`,
/// which cannot resolve (a file has no children). Per the issue, this
/// asserts the FAILURE itself, not esbuild's message text.
#[test]
fn plugin_alias_prefix_with_slash_still_fails_from_node_modules_entrypoint() {
    let Some(esbuild) = locate_esbuild() else {
        eprintln!("[node_modules_plugin_alias] no esbuild binary available; skipping.");
        return;
    };

    let tmp = tempfile::tempdir().expect("tempdir");
    let root = tmp.path().to_path_buf();
    let island_path = write_node_modules_island(
        &root,
        "import Marker from \"@/stub/deeper\";\n\
         export const Chrome = () => <Marker />;\n",
    );
    let target = write_single_file_alias_target(&root, "NodeModulesAliasMarker");

    let cfg = EsbuildSubprocessConfig {
        extra_args: preact_externals(),
        ..EsbuildSubprocessConfig::default()
    }
    .with_binary_path(esbuild)
    .with_working_dir(&root)
    .with_alias_entries(vec![(
        "@/stub".to_string(),
        target.to_string_lossy().into_owned(),
    )]);
    let bundler = EsbuildSubprocessBundler::new(cfg);
    let bundle_cfg = BundleConfig::default().with_outdir(root.join("dist"));

    bundler
        .bundle(&[Island::new("Chrome", &island_path)], &bundle_cfg)
        .expect_err(
            "#269 + #3002: single-file alias `@/stub` must NOT match \
             `@/stub/deeper`, even via the node_modules `--alias` fallback.",
        );
}

/// **Directory-target alias — behaviour unchanged from today.**
///
/// A directory-shaped alias never qualifies for the `--alias` fallback
/// (#3002's `is_file()` gate), so it stays tsconfig-paths-only exactly as
/// before this change. From a node_modules-resident importer the tsconfig
/// is never consulted, so the import must still fail to resolve — proving
/// #3002 did not widen the fallback beyond single-file targets.
