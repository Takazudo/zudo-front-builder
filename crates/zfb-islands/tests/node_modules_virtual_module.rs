//! Regression tests for #1263 (supersedes #1258): a route/island
//! entrypoint whose realpath is **under `node_modules`** must be able to
//! `import` a plugin-registered `virtual:*` module and bundle.
//!
//! ## Why the existing exact-match coverage missed this
//!
//! `exact_match_resolution.rs` registers virtual modules and imports them
//! from an island under `<root>/components/` — i.e. NOT under
//! `node_modules`. Those imports resolve through the synthetic tsconfig's
//! `compilerOptions.paths`. But esbuild does **not** apply
//! `compilerOptions.paths` to a source file resident under `node_modules`:
//! its resolver's `tsConfigForDir` returns `nil` the moment
//! `isInsideNodeModules` is true, *before* consulting the `--tsconfig` /
//! `--tsconfig-raw` override. So a preset that registers `injectRoute`
//! with an entrypoint installed under
//! `node_modules/@takazudo/zudo-doc/dist/routes/_chrome.js` hit
//! `esbuild [ERROR] Could not resolve "virtual:foo"`.
//!
//! The fix emits each virtual module ALSO as an esbuild
//! `--alias:<spec>=<tmp.mjs>` flag (`--alias` is not node_modules-gated),
//! which is exact-match-safe for virtual modules because their target is a
//! single `.mjs` file — see
//! `zfb_plugin_resolver::ResolverInputs::virtual_module_alias_args`.
//!
//! Esbuild gating mirrors the sibling tests: skip with a printed note when
//! no binary is available.

use std::fs;
use std::path::PathBuf;

use zfb_islands::{
    BundleConfig, ClientBundler, EsbuildSubprocessBundler, EsbuildSubprocessConfig, Island,
};
use zfb_test_utils::locate_esbuild;

/// Lay down an island TSX file whose realpath is under
/// `<root>/node_modules/...` — the exact #1263 shape (a published preset's
/// route entrypoint). Returns the absolute path to that file.
fn write_node_modules_island(root: &std::path::Path, island_source: &str) -> PathBuf {
    let nm_routes = root.join("node_modules/@scope/preset/dist/routes");
    fs::create_dir_all(&nm_routes).unwrap();
    let island_path = nm_routes.join("_chrome.tsx");
    fs::write(&island_path, island_source).unwrap();
    island_path
}

fn preact_externals() -> Vec<std::ffi::OsString> {
    vec![
        std::ffi::OsString::from("--external:preact"),
        std::ffi::OsString::from("--external:preact/*"),
        std::ffi::OsString::from("--external:@takazudo/*"),
    ]
}

/// **Primary #1263 gate — happy path.**
///
/// An island whose realpath is under `node_modules` imports the registered
/// `virtual:foo`. Bundling must succeed and the virtual module's source
/// (its exported marker) must reach the bundle. On `main` this fails with
/// `Could not resolve "virtual:foo"`.
#[test]
fn virtual_module_resolves_from_node_modules_entrypoint() {
    let Some(esbuild) = locate_esbuild() else {
        eprintln!("[node_modules_virtual_module] no esbuild binary available; skipping.");
        return;
    };

    let tmp = tempfile::tempdir().expect("tempdir");
    let root = tmp.path().to_path_buf();
    let island_path = write_node_modules_island(
        &root,
        "import Marker from \"virtual:foo\";\n\
         export const Chrome = () => <Marker />;\n",
    );

    let cfg = EsbuildSubprocessConfig {
        extra_args: preact_externals(),
        ..EsbuildSubprocessConfig::default()
    }
    .with_binary_path(esbuild)
    .with_working_dir(&root)
    .with_virtual_modules(vec![(
        "virtual:foo".to_string(),
        "export default function NodeModulesVirtualMarker() { return null; }\n".to_string(),
    )]);
    let bundler = EsbuildSubprocessBundler::new(cfg);
    let bundle_cfg = BundleConfig::default().with_outdir(root.join("dist"));

    let out = bundler
        .bundle(&[Island::new("Chrome", &island_path)], &bundle_cfg)
        .expect(
            "#1263: a route entrypoint whose realpath is under node_modules must \
             resolve a registered `virtual:foo` import (the synthetic tsconfig is \
             not applied to node_modules files; the `--alias` fallback must be).",
        );
    let body = String::from_utf8(out.bytes).expect("bundled bytes are valid UTF-8");
    assert!(
        body.contains("NodeModulesVirtualMarker"),
        "the virtual module's source must be bundled into a node_modules \
         entrypoint's output; got:\n{body}"
    );
}

/// **Exact-match preserved through the node_modules `--alias` path.**
///
/// The same node_modules entrypoint imports `virtual:foo/bar` (one slash
/// too many). The `--alias` fallback must NOT silently resolve it: the
/// target is a single `.mjs` file, so `virtual:foo/bar` remaps to
/// `<tmp>.mjs/bar` and fails. esbuild reports the failure with the
/// original specifier visible via its `(originally ...)` clause, so #269 is
/// not regressed even for node_modules-resident importers.
#[test]
fn virtual_module_prefix_with_slash_still_fails_from_node_modules_entrypoint() {
    let Some(esbuild) = locate_esbuild() else {
        eprintln!("[node_modules_virtual_module] no esbuild binary available; skipping.");
        return;
    };

    let tmp = tempfile::tempdir().expect("tempdir");
    let root = tmp.path().to_path_buf();
    let island_path = write_node_modules_island(
        &root,
        "import Marker from \"virtual:foo/bar\";\n\
         export const Chrome = () => <Marker />;\n",
    );

    let cfg = EsbuildSubprocessConfig {
        extra_args: preact_externals(),
        ..EsbuildSubprocessConfig::default()
    }
    .with_binary_path(esbuild)
    .with_working_dir(&root)
    .with_virtual_modules(vec![(
        "virtual:foo".to_string(),
        "export default function Foo() { return null; }\n".to_string(),
    )]);
    let bundler = EsbuildSubprocessBundler::new(cfg);
    let bundle_cfg = BundleConfig::default().with_outdir(root.join("dist"));

    let err = bundler
        .bundle(&[Island::new("Chrome", &island_path)], &bundle_cfg)
        .expect_err(
            "#269 + #1263: virtual module `virtual:foo` must NOT match \
             `virtual:foo/bar`, even via the node_modules `--alias` fallback.",
        );
    let msg = format!("{err:#}");
    assert!(
        msg.contains("virtual:foo/bar"),
        "esbuild error should still name the unresolved specifier \
         `virtual:foo/bar` (esbuild keeps it via its `(originally ...)` \
         clause for aliased failures). Got: {msg}"
    );
}
