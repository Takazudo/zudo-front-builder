import {
  ARCHITECTURE_GROUPS,
  BUILD_GROUPS,
  DEPLOY_SLUGS,
  WIND_ENTRY_SLUGS,
  WIND_LEARN_SLUGS,
  WIND_UTILITY_GROUPS,
} from "./navigation-groups.mjs";

const WIND_ROOT_SLUG = "zudo-wind";
const ARCHITECTURE_ROOT_SLUG = "architecture";
const BUILD_ROOT_SLUG = "build-with-zfb";
const DEPLOY_ROOT_SLUG = "deploy-embed";

// Editorial parent → ordered members. Members are often URL siblings of their
// parent (`utilities/background` under `utilities/surfaces-borders`), so the
// hierarchy comes from this shared membership source, never from URL segments.
const WIND_EDITORIAL_MEMBERS = new Map([
  [WIND_ROOT_SLUG, WIND_ENTRY_SLUGS],
  ["zudo-wind/learn", WIND_LEARN_SLUGS],
  ["zudo-wind/utilities", WIND_UTILITY_GROUPS.map((group) => group.slug)],
  ...WIND_UTILITY_GROUPS.map((group) => [group.slug, group.members]),
]);

// Group landing pages are URL siblings of their articles on disk, so a plain
// autogenerated directory stays flat; the groups' real pages become the parents.
function groupedMembers(rootSlug, groups) {
  return new Map([
    [rootSlug, groups.map((group) => group.slug)],
    ...groups.map((group) => [group.slug, group.members]),
  ]);
}
const ARCHITECTURE_EDITORIAL_MEMBERS = groupedMembers(ARCHITECTURE_ROOT_SLUG, ARCHITECTURE_GROUPS);
const BUILD_EDITORIAL_MEMBERS = groupedMembers(BUILD_ROOT_SLUG, BUILD_GROUPS);
const DEPLOY_EDITORIAL_MEMBERS = new Map([[DEPLOY_ROOT_SLUG, DEPLOY_SLUGS]]);

function slugsOf(members) {
  return new Set([...members].flatMap(([parent, children]) => [parent, ...children]));
}
const ARCHITECTURE_SLUGS = slugsOf(ARCHITECTURE_EDITORIAL_MEMBERS);
const BUILD_SLUGS = slugsOf(BUILD_EDITORIAL_MEMBERS);

// Occurrence indexes from `rootSlug` to `slug` along an editorial tree.
function editorialPath(members, rootSlug, slug) {
  if (slug === rootSlug) return [];
  for (const [parent, children] of members) {
    const index = children.indexOf(slug);
    if (index >= 0) return [...editorialPath(members, rootSlug, parent), index];
  }
  throw new Error(`No editorial ${rootSlug} parent for ${slug}`);
}

function windScope(id, rootSlug) {
  return {
    id,
    navSection: WIND_ROOT_SLUG,
    rootSlug,
    editorialRootSlug: WIND_ROOT_SLUG,
    memberSlugs: WIND_EDITORIAL_MEMBERS.get(rootSlug),
    path: editorialPath(WIND_EDITORIAL_MEMBERS, WIND_ROOT_SLUG, rootSlug),
    initialPathMode: "node",
  };
}

const entryScope = windScope("wind", WIND_ROOT_SLUG);
const learnScope = windScope("wind-learn", "zudo-wind/learn");
const utilitiesScope = windScope("wind-utilities", "zudo-wind/utilities");
const groupScopes = WIND_UTILITY_GROUPS.map((group) => windScope(group.id, group.slug));

// Architecture's landing page is its own linked root view; every other
// Architecture page starts at the root's four linked group rows, and native
// Broaden reaches the real landing page. Both views share one forest, so
// reader choices carry between them.
const architectureOverviewScope = {
  id: "architecture-overview",
  navSection: ARCHITECTURE_ROOT_SLUG,
  rootSlug: ARCHITECTURE_ROOT_SLUG,
  editorialRootSlug: ARCHITECTURE_ROOT_SLUG,
  path: [],
  initialPathMode: "node",
};
const architectureScope = {
  ...architectureOverviewScope,
  id: "architecture",
  initialPathMode: "children",
};
// Build keeps its landing page as the visible root row above its six groups.
const buildScope = {
  id: "build",
  navSection: BUILD_ROOT_SLUG,
  rootSlug: BUILD_ROOT_SLUG,
  editorialRootSlug: BUILD_ROOT_SLUG,
  path: [],
  initialPathMode: "node",
};
// Deploy & Embed is its own highest scope: the real landing row above its four
// leaves. Three ways to run zfb stays listed here but is owned by Architecture.
const deployScope = {
  id: "deploy",
  navSection: DEPLOY_ROOT_SLUG,
  rootSlug: DEPLOY_ROOT_SLUG,
  editorialRootSlug: DEPLOY_ROOT_SLUG,
  path: [],
  initialPathMode: "node",
};

const EDITORIAL_MEMBERS = new Map([
  [WIND_ROOT_SLUG, WIND_EDITORIAL_MEMBERS],
  [ARCHITECTURE_ROOT_SLUG, ARCHITECTURE_EDITORIAL_MEMBERS],
  [BUILD_ROOT_SLUG, BUILD_EDITORIAL_MEMBERS],
  [DEPLOY_ROOT_SLUG, DEPLOY_EDITORIAL_MEMBERS],
]);

/**
 * The sidebar section that owns a page, independent of the link that reached
 * it. Architecture owns its routes even when Build or Deploy also lists them;
 * practical guides keep their Deploy/Build membership without moving URLs.
 */
export function canonicalNavSection(currentSlug = "", navSection) {
  if (
    currentSlug === ARCHITECTURE_ROOT_SLUG ||
    currentSlug.startsWith(`${ARCHITECTURE_ROOT_SLUG}/`)
  )
    return ARCHITECTURE_ROOT_SLUG;
  if (DEPLOY_SLUGS.includes(currentSlug)) return DEPLOY_ROOT_SLUG;
  if (currentSlug.startsWith("guides/") && BUILD_SLUGS.has(currentSlug)) return BUILD_ROOT_SLUG;
  return navSection;
}

export function resolveNavigationScope(currentSlug, navSection) {
  if (navSection === ARCHITECTURE_ROOT_SLUG) {
    if (currentSlug === ARCHITECTURE_ROOT_SLUG) return architectureOverviewScope;
    return ARCHITECTURE_SLUGS.has(currentSlug) ? architectureScope : undefined;
  }
  if (navSection === BUILD_ROOT_SLUG) return BUILD_SLUGS.has(currentSlug) ? buildScope : undefined;
  if (navSection === DEPLOY_ROOT_SLUG)
    return (currentSlug === DEPLOY_ROOT_SLUG || DEPLOY_SLUGS.includes(currentSlug)) &&
      canonicalNavSection(currentSlug, navSection) === DEPLOY_ROOT_SLUG
      ? deployScope
      : undefined;
  if (navSection !== WIND_ROOT_SLUG) return undefined;
  // Coming from Tailwind keeps the entry view without being one of its menu members.
  if (
    [WIND_ROOT_SLUG, "zudo-wind/compatibility", "zudo-wind/coming-from-tailwind"].includes(
      currentSlug,
    )
  )
    return entryScope;
  if (currentSlug === learnScope.rootSlug || WIND_LEARN_SLUGS.includes(currentSlug))
    return learnScope;
  if (currentSlug === utilitiesScope.rootSlug) return utilitiesScope;
  return groupScopes.find(
    (scope) => scope.rootSlug === currentSlug || scope.memberSlugs.includes(currentSlug),
  );
}

/** Native sidebar definition for a scope's dedicated single-root editorial forest. */
export function sidebarDefinitionFor(scope) {
  return {
    items: [{ type: "autogenerated" }],
    initialPath: [0, ...scope.path],
    initialPathMode: scope.initialPathMode,
  };
}

/**
 * Rebuild a complete editorial forest from the native nav tree.
 * Every node keeps its native label, href and metadata; its children are
 * exactly its editorial members. A node without membership is an editorial
 * leaf: its native URL descendants are dropped, so a page reaches the sidebar
 * only through navigation-groups.mjs and a cross-link (Markdown Features,
 * zudo-wind) never imports its whole section. The input tree is not mutated.
 */
export function buildEditorialForest(tree, rootSlug) {
  const members = EDITORIAL_MEMBERS.get(rootSlug);
  if (!members) throw new Error(`No editorial navigation for ${rootSlug}`);
  const nodes = new Map();
  function visit(children) {
    for (const node of children) {
      nodes.set(node.slug, node);
      visit(node.children);
    }
  }
  visit(tree);
  function build(slug) {
    const node = nodes.get(slug);
    if (!node?.hasPage || !node.href)
      throw new Error(`Editorial navigation requires routed node ${slug}`);
    const children = members.get(slug);
    return { ...node, children: children ? children.map(build) : [] };
  }
  return [build(rootSlug)];
}

export function buildWindEditorialForest(tree) {
  return buildEditorialForest(tree, WIND_ROOT_SLUG);
}

export function editorialForestFor(scope, tree) {
  return buildEditorialForest(tree, scope.editorialRootSlug);
}
