export type CssProperty =
  | (typeof cssProperties)[number]
  | (typeof vendorProperties)[number]
  | `--${string}`;
type UnitlessProperty = (typeof unitlessProperties)[number];
type ZeroOnlyProperty = Exclude<CssProperty, UnitlessProperty | `--${string}`>;
export type CSSProperties = Readonly<
  Partial<Record<ZeroOnlyProperty, string | 0 | null | undefined>> &
    Partial<Record<UnitlessProperty | `--${string}`, string | number | null | undefined>>
>;

const known = new Set<string>([...cssProperties, ...vendorProperties]);
const unitless = new Set<string>(unitlessProperties);
const customName = /^--[a-zA-Z0-9_-]+$/;

export function serializeStyle(value: unknown): string {
  if (typeof value === "string") return value;
  if (
    value === null ||
    typeof value !== "object" ||
    Object.getPrototypeOf(value) !== Object.prototype
  )
    throw new TypeError("ZR_STYLE: style must be a string or plain object");
  let result = "";
  for (const [name, entry] of Object.entries(value)) {
    if (!known.has(name) && !customName.test(name))
      throw new TypeError(
        `ZR_STYLE: unsupported property ${name}; use a supported CSS-spelled name`,
      );
    if (entry == null) continue;
    if (typeof entry === "string") {
      result += `${name}:${entry};`;
      continue;
    }
    if (typeof entry !== "number" || !Number.isFinite(entry))
      throw new TypeError(`ZR_STYLE: invalid value for ${name}; use a string or finite number`);
    if (entry !== 0 && !unitless.has(name) && !name.startsWith("--"))
      throw new TypeError(`ZR_STYLE: nonzero numeric ${name} requires explicit units in a string`);
    result += `${name}:${entry};`;
  }
  return result;
}
